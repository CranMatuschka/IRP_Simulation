function runTruthResidualStatisticsRegression()
    ProjectPathManager.addProjectPaths();

    expectedTroposphereSigma_m = 1.20;
    expectedIonosphereSigma_m = 1.60;
    expectedTotalSigma_m = hypot( ...
        expectedTroposphereSigma_m, ...
        expectedIonosphereSigma_m);

    sim = runTruthResidualStatisticsScenarioForTest( ...
        93001, ...
        expectedTroposphereSigma_m, ...
        expectedIonosphereSigma_m);

    troposphereSamples_m = ...
        sim.history.errors.troposphere.stochasticResidualByTower_m(:);

    ionosphereSamples_m = ...
        sim.history.errors.ionosphere.stochasticResidualByTower_m(:);

    totalSamples_m = ...
        sim.history.errors.atmosphere.stochasticResidualByTower_m(:);

    validSamples = ...
        isfinite(troposphereSamples_m) & ...
        isfinite(ionosphereSamples_m) & ...
        isfinite(totalSamples_m);

    troposphereSamples_m = troposphereSamples_m(validSamples);
    ionosphereSamples_m = ionosphereSamples_m(validSamples);
    totalSamples_m = totalSamples_m(validSamples);

    sampleCount = numel(totalSamples_m);

    assert(sampleCount >= 500, ...
        'Truth residual statistics regression requires at least 500 samples.');

    assert(max(abs(totalSamples_m - ...
        (troposphereSamples_m + ionosphereSamples_m))) < 1e-12, ...
        'Total truth residual samples must equal troposphere plus ionosphere samples.');

    troposphereMean_m = mean(troposphereSamples_m, 'omitnan');
    ionosphereMean_m = mean(ionosphereSamples_m, 'omitnan');
    totalMean_m = mean(totalSamples_m, 'omitnan');

    troposphereStd_m = std(troposphereSamples_m, 0, 'omitnan');
    ionosphereStd_m = std(ionosphereSamples_m, 0, 'omitnan');
    totalStd_m = std(totalSamples_m, 0, 'omitnan');

    troposphereRms_m = sqrt(mean(troposphereSamples_m.^2, 'omitnan'));
    ionosphereRms_m = sqrt(mean(ionosphereSamples_m.^2, 'omitnan'));
    totalRms_m = sqrt(mean(totalSamples_m.^2, 'omitnan'));

    meanToleranceFactor = 4.0 / sqrt(double(sampleCount));

    assert(abs(troposphereMean_m) < ...
            max(0.08, meanToleranceFactor * expectedTroposphereSigma_m), ...
        'Troposphere truth residual mean should be statistically close to zero.');

    assert(abs(ionosphereMean_m) < ...
            max(0.08, meanToleranceFactor * expectedIonosphereSigma_m), ...
        'Ionosphere truth residual mean should be statistically close to zero.');

    assert(abs(totalMean_m) < ...
            max(0.12, meanToleranceFactor * expectedTotalSigma_m), ...
        'Total truth residual mean should be statistically close to zero.');

    assert(abs(troposphereStd_m - expectedTroposphereSigma_m) / ...
            expectedTroposphereSigma_m < 0.20, ...
        'Troposphere truth residual standard deviation should match configured sigma.');

    assert(abs(ionosphereStd_m - expectedIonosphereSigma_m) / ...
            expectedIonosphereSigma_m < 0.20, ...
        'Ionosphere truth residual standard deviation should match configured sigma.');

    assert(abs(totalStd_m - expectedTotalSigma_m) / ...
            expectedTotalSigma_m < 0.20, ...
        'Total truth residual standard deviation should match RSS component sigma.');

    assert(abs(troposphereRms_m - expectedTroposphereSigma_m) / ...
            expectedTroposphereSigma_m < 0.20, ...
        'Troposphere truth residual RMS should match configured sigma.');

    assert(abs(ionosphereRms_m - expectedIonosphereSigma_m) / ...
            expectedIonosphereSigma_m < 0.20, ...
        'Ionosphere truth residual RMS should match configured sigma.');

    assert(abs(totalRms_m - expectedTotalSigma_m) / ...
            expectedTotalSigma_m < 0.20, ...
        'Total truth residual RMS should match RSS component sigma.');

    troposphereCorrelationSamples_m = troposphereSamples_m(:);
    ionosphereCorrelationSamples_m = ionosphereSamples_m(:);

    validCorrelationSamples = ...
        isfinite(troposphereCorrelationSamples_m) & ...
        isfinite(ionosphereCorrelationSamples_m);

    troposphereCorrelationSamples_m = ...
        troposphereCorrelationSamples_m(validCorrelationSamples);

    ionosphereCorrelationSamples_m = ...
        ionosphereCorrelationSamples_m(validCorrelationSamples);

    assert(numel(troposphereCorrelationSamples_m) >= 2, ...
        'Truth residual correlation check requires at least two valid samples.');

    troposphereCentered_m = ...
        troposphereCorrelationSamples_m - ...
        mean(troposphereCorrelationSamples_m, 'omitnan');

    ionosphereCentered_m = ...
        ionosphereCorrelationSamples_m - ...
        mean(ionosphereCorrelationSamples_m, 'omitnan');

    correlationDenominator = ...
        sqrt(sum(troposphereCentered_m.^2) * ...
             sum(ionosphereCentered_m.^2));

    assert(correlationDenominator > 0.0, ...
        'Truth residual correlation denominator should be positive.');

    residualCorrelation = ...
        sum(troposphereCentered_m .* ionosphereCentered_m) / ...
        correlationDenominator;

    assert(abs(residualCorrelation) < 0.20, ...
        'Troposphere and ionosphere truth residual samples should be approximately independent.');
    reportContext = ReportDataBuilder.fromSimulation(sim);
    assert(isequaln(reportContext.history, sim.history));
    assert(abs(hypot(expectedTroposphereSigma_m, expectedIonosphereSigma_m) - ...
        expectedTotalSigma_m) < 1e-12, ...
        'Configured total residual sigma should be RSS.');
    assert(abs(std(troposphereCorrelationSamples_m, 0, 'omitnan') - ...
        troposphereStd_m) < 1e-12, ...
        'Troposphere residual std should match raw samples.');
    assert(abs(std(ionosphereCorrelationSamples_m, 0, 'omitnan') - ...
        ionosphereStd_m) < 1e-12, ...
        'Ionosphere residual std should match raw samples.');
    assert(~isfield(reportContext, 'stochastic_truth_residual_summary_table'), ...
        'Report context must not store derived stochastic residual tables.');

    disp("PASS: stochastic truth atmosphere residual statistics match configured sigmas.");
end

