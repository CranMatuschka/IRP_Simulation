function runResidualSigmaOverconfidenceRegression()
    ProjectPathManager.addProjectPaths();

    constants = struct( ...
        'speedOfLight_mps', 299792458.0, ...
        'earthRadius_m', 6378137.0);

    measurementSigma_m = 0.30;
    numericalSigmaFloor_m = 1.0e-4;

    scenarioCfg = struct();

    scenarioCfg.measurement = struct( ...
        'signalFrequency_Hz', 1575.42e6, ...
        'enableMeasurementNoise', false, ...
        'enableNoise', false, ...
        'enableElevationMask', false, ...
        'enableHardwareDelay', false, ...
        'enableMultipathDelay', false, ...
        'enableAntennaDelay', false, ...
        'enableSagnacCorrection', false, ...
        'enableLightTimeCorrection', false, ...
        'pseudorangeSigma_m', measurementSigma_m, ...
        'sigma_numerical_floor_m', numericalSigmaFloor_m);

    baseAtmosphereComponentCfg = struct( ...
        'enableTroposphere', true, ...
        'enableIonosphere', true, ...
        'troposphereModel', "constant", ...
        'ionosphereModel', "constant", ...
        'constantTroposphereDelay_m', 0.0, ...
        'constantIonosphereDelay_m', 0.0, ...
        'residualTroposphereSigma_m', 0.0, ...
        'residualIonosphereSigma_m', 0.0);

    highResidualAtmosphereComponentCfg = baseAtmosphereComponentCfg;
    highResidualAtmosphereComponentCfg.residualTroposphereSigma_m = 4.0;
    highResidualAtmosphereComponentCfg.residualIonosphereSigma_m = 3.0;

    lowAtmosphereCfg = struct();
    lowAtmosphereCfg.dataRoot = fullfile("data", "atmosphere");
    lowAtmosphereCfg.missingDataPolicy = "error";
    lowAtmosphereCfg.ionosphereShellHeight_m = 350000.0;
    lowAtmosphereCfg.truth = baseAtmosphereComponentCfg;
    lowAtmosphereCfg.model = baseAtmosphereComponentCfg;

    highAtmosphereCfg = lowAtmosphereCfg;
    highAtmosphereCfg.model = highResidualAtmosphereComponentCfg;

    truthAtmosphere = Atmosphere(lowAtmosphereCfg, constants, "truth");
    lowResidualModelAtmosphere = ...
        Atmosphere(lowAtmosphereCfg, constants, "model");

    highResidualModelAtmosphere = ...
        Atmosphere(highAtmosphereCfg, constants, "model");

    lowResidualMeasurementModel = MeasurementModel( ...
        scenarioCfg, ...
        constants.speedOfLight_mps, ...
        {}, ...
        [], ...
        [], ...
        truthAtmosphere, ...
        lowResidualModelAtmosphere, ...
        []);

    highResidualMeasurementModel = MeasurementModel( ...
        scenarioCfg, ...
        constants.speedOfLight_mps, ...
        {}, ...
        [], ...
        [], ...
        truthAtmosphere, ...
        highResidualModelAtmosphere, ...
        []);

    expectedAtmosphereVariance_m2 = 4.0^2 + 3.0^2;

    assert(lowResidualMeasurementModel.atmosphereResidualVariance_m2() == 0.0, ...
        'Low-residual model should have zero atmospheric residual variance.');

    assert(abs(highResidualMeasurementModel.atmosphereResidualVariance_m2() - ...
        expectedAtmosphereVariance_m2) < 1e-12, ...
        'High-residual model should use sigma_tropo^2 + sigma_iono^2.');

    measurementTowerIndex = [1; 1; 2; 2; 3; 3];

    lowR = lowResidualMeasurementModel.measurementCovariance( ...
        measurementTowerIndex, ...
        true, ...
        0.0);

    highR = highResidualMeasurementModel.measurementCovariance( ...
        measurementTowerIndex, ...
        true, ...
        0.0);

    assert(all(eig((lowR + lowR.') / 2.0) > 0.0), ...
        'Low-residual covariance must be positive definite.');

    assert(all(eig((highR + highR.') / 2.0) > 0.0), ...
        'High-residual covariance must be positive definite.');

    assert(all(diag(highR) > diag(lowR)), ...
        'Atmospheric residual sigma should increase innovation covariance diagonal.');

    assert(abs(highR(1, 2) - expectedAtmosphereVariance_m2) < 1e-12, ...
        'Same-tower high-residual covariance should contain atmosphere common variance.');

    assert(abs(highR(1, 3)) < 1e-12, ...
        'Different-tower high-residual covariance should remain zero.');

    assert(abs(lowR(1, 2)) < 1e-12, ...
        'Low-residual same-tower off-diagonal covariance should be zero.');

    commonAtmosphereInnovation_m = 4.0 * ones(numel(measurementTowerIndex), 1);

    lowNis = ...
        commonAtmosphereInnovation_m.' * ...
        (lowR \ commonAtmosphereInnovation_m);

    highNis = ...
        commonAtmosphereInnovation_m.' * ...
        (highR \ commonAtmosphereInnovation_m);

    dof = numel(measurementTowerIndex);

    lowNisPerDof = lowNis / dof;
    highNisPerDof = highNis / dof;

    lowNormalizedInnovationRms = sqrt(lowNisPerDof);
    highNormalizedInnovationRms = sqrt(highNisPerDof);

    assert(highNis < lowNis, ...
        'Larger atmospheric residual covariance should reduce NIS for the same common-mode residual.');

    assert(highNisPerDof < lowNisPerDof, ...
        'Larger atmospheric residual covariance should reduce NIS per degree of freedom.');

    assert(highNormalizedInnovationRms < lowNormalizedInnovationRms, ...
        'Larger atmospheric residual covariance should reduce normalized innovation RMS.');

    assert(highNis < 0.05 * lowNis, ...
        'Atmospheric residual covariance should strongly reduce overconfidence for common-mode atmosphere residuals.');

    deterministicInnovationUnchanged_m = ...
        commonAtmosphereInnovation_m - commonAtmosphereInnovation_m;

    assert(all(abs(deterministicInnovationUnchanged_m) < 1e-12), ...
        'Changing residual sigma must not change the deterministic innovation vector itself.');

    disp("PASS: atmospheric residual sigma reduces EKF overconfidence.");
end

