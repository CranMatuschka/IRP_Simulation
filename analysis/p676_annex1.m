function F = lineShape_(f, f0, df, delta)
% eq (5): line shape with overlap correction, both resonance and image terms.
    fm = f0 - f;
    fp = f0 + f;
    F  = (f ./ f0) .* ( (df - delta.*fm) ./ (fm.^2 + df.^2) ...
                      + (df - delta.*fp) ./ (fp.^2 + df.^2) );
end
