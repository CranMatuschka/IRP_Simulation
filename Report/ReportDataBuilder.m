classdef ReportDataBuilder
    %REPORTDATABUILDER Builds reportData from a completed ReverseGnssSimulation.
    %
    % This class owns the mapping from simulation state/history/results into
    % the reportData struct consumed by generateReport.m. It should not create
    % final report tables or figures.

    methods (Static)
        function reportData = fromSimulation(sim)
            xHist = sim.history.x;
            truthHist = sim.history.truth;
            Pdiag = sim.history.covariance_diag;

            reportData = struct();
            reportData.error_budget_status = ...
                ResultBuilder.errorBudgetStatus(sim);

            reportData.time_vec = sim.time_s;
            reportData.total_time_hours = max(sim.time_s) / 3600.0;
            reportData.dt = sim.dt;
            reportData.c = sim.c;
            reportData.num_towers = sim.numTowers;
            reportData.R_earth = sim.constants.earthRadius_m;
            reportData.oscillators = sim.simConfig.clockLibrary;
            reportData.towers = ReportDataBuilder.reportTowers(sim);
            reportData.tower_names = sim.towerNames;
            reportData.receiver_names = sim.receiverNames;

            % Raw inputs used by generateReport.m to build report-specific tables.
            reportData.asset_name = string(sim.assetConfig.name);
            reportData.state_names = StateIndexFactory.stateNames( ...
                sim.towerNames, GroundTimingNetwork.towerClockEkfEnabled(sim.cfg));
            reportData.state_dim = sim.stateDim;
            reportData.state_index = sim.idx;
            reportData.enable_tower_clock_ekf = GroundTimingNetwork.towerClockEkfEnabled(sim.cfg);
            reportData.num_receivers = sim.numReceivers;
            reportData.receiver_offsets_body_m = sim.receiverOffsetsBody_m;
            reportData.initial_truth_position_eci_m = sim.initialTruth0(sim.idx.pos);
            reportData.initial_est_position_eci_m = sim.initialX0(sim.idx.pos);
            reportData.observability_normal_matrix = sim.observabilityNormalMatrix;

            reportData.ekf_pos_error_m = xHist(sim.idx.pos, :) - truthHist(sim.idx.pos, :);
            reportData.ekf_pos_sigma_m = sqrt(max(Pdiag(sim.idx.pos, :), 0));
            reportData.ekf_clock_error_ps = ...
                (xHist(sim.idx.rxClockBias, :) - truthHist(sim.idx.rxClockBias, :)) ./ sim.c .* 1e12;
            reportData.ekf_clock_sigma_ps = ...
                sqrt(max(Pdiag(sim.idx.rxClockBias, :), 0)) ./ sim.c .* 1e12;
            reportData.true_clock_bias_ps = truthHist(sim.idx.rxClockBias, :) ./ sim.c .* 1e12;
            reportData.est_clock_bias_ps = xHist(sim.idx.rxClockBias, :) ./ sim.c .* 1e12;

            if GroundTimingNetwork.towerClockEkfEnabled(sim.cfg)
                reportData.est_tower_clock_bias_ps = ...
                    xHist(sim.idx.towerClockBias, :) ./ sim.c .* 1e12;

                reportData.true_tower_clock_bias_ps = ...
                    truthHist(sim.idx.towerClockBias, :) ./ sim.c .* 1e12;

                reportData.est_tower_clock_drift_psps = ...
                    xHist(sim.idx.towerClockDrift, :) ./ sim.c .* 1e12;

                reportData.true_tower_clock_drift_psps = ...
                    truthHist(sim.idx.towerClockDrift, :) ./ sim.c .* 1e12;
            end

            reportData.innovation_rms_m = sim.history.innovation_rms_m;
            reportData.postfit_innovation_rms_m = sim.history.postfit_innovation_rms_m;
            reportData.nis_history = sim.history.nis_history;
            reportData.nis_degrees_of_freedom = sim.history.measurement_count;
            reportData.innovation_covariance_mean_variance_m2 = ...
                sim.history.innovation_covariance_mean_variance_m2;

            reportData.innovation_covariance_min_variance_m2 = ...
                sim.history.innovation_covariance_min_variance_m2;

            reportData.innovation_covariance_max_variance_m2 = ...
                sim.history.innovation_covariance_max_variance_m2;

            reportData.innovation_covariance_mean_sigma_m = ...
                sqrt(max(reportData.innovation_covariance_mean_variance_m2, 0.0));

            reportData.innovation_covariance_min_sigma_m = ...
                sqrt(max(reportData.innovation_covariance_min_variance_m2, 0.0));

            reportData.innovation_covariance_max_sigma_m = ...
                sqrt(max(reportData.innovation_covariance_max_variance_m2, 0.0));

            reportData.nis_per_degree_of_freedom = ...
                sim.history.nis_per_degree_of_freedom;
            reportData.measurement_covariance_range_mean_variance_m2 = ...
                sim.history.measurement_covariance_range_mean_variance_m2;
            reportData.measurement_covariance_range_max_offdiag_m2 = ...
                sim.history.measurement_covariance_range_max_offdiag_m2;
            reportData.measurement_covariance_range_dimension = ...
                sim.history.measurement_covariance_range_dimension;

            reportData.measurement_covariance_update_mean_variance_m2 = ...
                sim.history.measurement_covariance_update_mean_variance_m2;
            reportData.measurement_covariance_update_max_offdiag_m2 = ...
                sim.history.measurement_covariance_update_max_offdiag_m2;
            reportData.measurement_covariance_update_dimension = ...
                sim.history.measurement_covariance_update_dimension;
            reportData.normalized_innovation_rms = ...
                sim.history.normalized_innovation_rms;
            reportData.sat_pos_history_m = sim.history.sat_pos_history_m;
            reportData.towers_eci_first_m = sim.towersEciFirst_m;
            reportData.final_position_error_m = norm(reportData.ekf_pos_error_m(:, end));
            reportData.final_clock_error_ps = reportData.ekf_clock_error_ps(end);
            reportData.final_innovation_rms_m = sim.history.innovation_rms_m(end);

            reportData.attitude_truth_deg = rad2deg(truthHist(sim.idx.att, :));
            reportData.attitude_est_deg = rad2deg(xHist(sim.idx.att, :));
            reportData.attitude_error_deg = rad2deg( ...
                FrameGeometry.wrapToPi(xHist(sim.idx.att, :) - truthHist(sim.idx.att, :)));
            reportData.attitude_sigma_deg = rad2deg(sqrt(max(Pdiag(sim.idx.att, :), 0)));
            reportData.attitude_state_names = ["roll"; "pitch"; "yaw"];
            reportData.attitude_frame = "body-to-ECI Euler view of q_BI";

            reportData.angular_velocity_truth_degps = rad2deg(truthHist(sim.idx.omega, :));
            reportData.angular_velocity_est_degps = rad2deg(xHist(sim.idx.omega, :));
            reportData.angular_velocity_error_degps = ...
                rad2deg(xHist(sim.idx.omega, :) - truthHist(sim.idx.omega, :));
            reportData.angular_velocity_sigma_degps = ...
                rad2deg(sqrt(max(Pdiag(sim.idx.omega, :), 0)));
            reportData.angular_velocity_state_names = ["omega_x"; "omega_y"; "omega_z"];
            reportData.final_attitude_error_norm_deg = norm(reportData.attitude_error_deg(:, end));
            reportData.final_angular_velocity_error_norm_degps = ...
                norm(reportData.angular_velocity_error_degps(:, end));

            reportData.final_H_pos_rank = sim.history.H_pos_rank_history(end);
            reportData.final_H_att_rank = sim.history.H_att_rank_history(end);
            reportData.final_H_pos_att_clock_rank = sim.history.H_pos_att_clock_rank_history(end);
            reportData.final_H_pos_column_norm = sim.history.H_pos_column_norm_history(:, end);
            reportData.final_H_att_column_norm = sim.history.H_att_column_norm_history(:, end);
            reportData.final_H_rx_clock_bias_column_norm = ...
                sim.history.H_rx_clock_bias_column_norm_history(end);

            reportData.H_rank_history = sim.history.H_rank_history;
            reportData.H_pos_rank_history = sim.history.H_pos_rank_history;
            reportData.H_att_rank_history = sim.history.H_att_rank_history;
            reportData.H_pos_att_clock_rank_history = sim.history.H_pos_att_clock_rank_history;
            reportData.H_rx_clock_bias_column_norm_history = ...
                sim.history.H_rx_clock_bias_column_norm_history;
            reportData.pseudorange_measurement_count = sim.history.pseudorange_measurement_count;

            reportData.final_H_rank = sim.history.H_rank_history(end);
            reportData.H_row_count_history = sim.history.measurement_count;
            reportData.H_column_count_history = sim.stateDim * ones(1, sim.numSteps);
            reportData.H_rank_to_state_dim_history = ...
                sim.history.H_rank_history ./ max(sim.stateDim, 1);
            reportData.H_state_deficiency_history = ...
                sim.stateDim - sim.history.H_rank_history;
            reportData.final_H_rows = sim.history.measurement_count(end);
            reportData.final_H_columns = sim.stateDim;
            reportData.final_H_rank_to_state_dim = reportData.final_H_rank / max(sim.stateDim, 1);
            reportData.final_H_state_deficiency = sim.stateDim - reportData.final_H_rank;

            reportData.true_ground_clock_bias_ps = sim.history.ground_clock_true_m ./ sim.c .* 1e12;
            reportData.tower_clock_correction_s = sim.history.ground_clock_correction_m ./ sim.c;
            reportData.tower_clock_correction_residual_s = ...
                sim.history.ground_clock_residual_m ./ sim.c;
            reportData.tower_clock_correction_sigma_s = ...
                ones(sim.numTowers, sim.numSteps) .* ...
                sqrt(GroundTimingNetwork.residualVariance_m2(sim.cfg, sim.c)) ./ sim.c;

            reportData.prefit_residual_by_receiver_tower_m = ...
                sim.history.prefit_residual_by_receiver_tower_m;
            reportData.postfit_residual_by_receiver_tower_m = ...
                sim.history.postfit_residual_by_receiver_tower_m;
            reportData.pseudorange_by_receiver_tower_m = ...
                sim.history.pseudorange_by_receiver_tower_m;
            reportData.true_range_by_receiver_tower_m = ...
                sim.history.true_range_by_receiver_tower_m;

            reportData.atmosphere = sim.history.atmosphere;
            reportData.propagation = sim.history.propagation;
            if isfield(sim.history, 'non_atmospheric')
                reportData.non_atmospheric = sim.history.non_atmospheric;
            end
            reportData.atmosphere_truth_delay_by_receiver_tower_m = ...
                sim.history.atmosphere_truth_delay_by_receiver_tower_m;
            reportData.atmosphere_truth_residual_by_tower_m = ...
                sim.history.atmosphere_truth_residual_by_tower_m;
            reportData.atmosphere_truth_total_by_receiver_tower_m = ...
                sim.history.atmosphere_truth_total_by_receiver_tower_m;
            reportData.atmosphere_truth_troposphere_by_receiver_tower_m = ...
                sim.history.atmosphere_truth_troposphere_by_receiver_tower_m;
            reportData.atmosphere_truth_ionosphere_by_receiver_tower_m = ...
                sim.history.atmosphere_truth_ionosphere_by_receiver_tower_m;
            reportData.atmosphere_truth_ionosphere_ipp_lat_deg_by_receiver_tower = ...
                sim.history.atmosphere_truth_ionosphere_ipp_lat_deg_by_receiver_tower;
            reportData.atmosphere_truth_ionosphere_ipp_lon_deg_by_receiver_tower = ...
                sim.history.atmosphere_truth_ionosphere_ipp_lon_deg_by_receiver_tower;
            reportData.atmosphere_truth_ionosphere_vtec_TECU_by_receiver_tower = ...
                sim.history.atmosphere_truth_ionosphere_vtec_TECU_by_receiver_tower;
            reportData.atmosphere_truth_ionosphere_stec_TECU_by_receiver_tower = ...
                sim.history.atmosphere_truth_ionosphere_stec_TECU_by_receiver_tower;
            reportData.atmosphere_truth_ionosphere_mapping_factor_by_receiver_tower = ...
                sim.history.atmosphere_truth_ionosphere_mapping_factor_by_receiver_tower;

            reportData.atmosphere_truth_ionosphere_frequency_Hz_by_receiver_tower = ...
                sim.history.atmosphere_truth_ionosphere_frequency_Hz_by_receiver_tower;
            reportData.atmosphere_truth_troposphere_pressure_hPa_by_receiver_tower = ...
                sim.history.atmosphere_truth_troposphere_pressure_hPa_by_receiver_tower;

            reportData.atmosphere_truth_troposphere_temperature_K_by_receiver_tower = ...
                sim.history.atmosphere_truth_troposphere_temperature_K_by_receiver_tower;

            reportData.atmosphere_truth_troposphere_relative_humidity_fraction_by_receiver_tower = ...
                sim.history.atmosphere_truth_troposphere_relative_humidity_fraction_by_receiver_tower;

            reportData.atmosphere_truth_troposphere_water_vapor_pressure_hPa_by_receiver_tower = ...
                sim.history.atmosphere_truth_troposphere_water_vapor_pressure_hPa_by_receiver_tower;

            reportData.atmosphere_truth_troposphere_zhd_m_by_receiver_tower = ...
                sim.history.atmosphere_truth_troposphere_zhd_m_by_receiver_tower;

            reportData.atmosphere_truth_troposphere_zwd_m_by_receiver_tower = ...
                sim.history.atmosphere_truth_troposphere_zwd_m_by_receiver_tower;

            reportData.atmosphere_truth_troposphere_mapping_hydrostatic_by_receiver_tower = ...
                sim.history.atmosphere_truth_troposphere_mapping_hydrostatic_by_receiver_tower;

            reportData.atmosphere_truth_troposphere_mapping_wet_by_receiver_tower = ...
                sim.history.atmosphere_truth_troposphere_mapping_wet_by_receiver_tower;

            reportData.atmosphere_truth_troposphere_slant_hydrostatic_m_by_receiver_tower = ...
                sim.history.atmosphere_truth_troposphere_slant_hydrostatic_m_by_receiver_tower;

            reportData.atmosphere_truth_troposphere_slant_wet_m_by_receiver_tower = ...
                sim.history.atmosphere_truth_troposphere_slant_wet_m_by_receiver_tower;
            reportData.atmosphere_truth_troposphere_residual_by_tower_m = ...
                sim.history.atmosphere_truth_troposphere_residual_by_tower_m;
            reportData.atmosphere_truth_ionosphere_residual_by_tower_m = ...
                sim.history.atmosphere_truth_ionosphere_residual_by_tower_m;
            reportData.atmosphere_truth_troposphere_total_by_receiver_tower_m = ...
                sim.history.atmosphere_truth_troposphere_total_by_receiver_tower_m;
            reportData.atmosphere_truth_ionosphere_total_by_receiver_tower_m = ...
                sim.history.atmosphere_truth_ionosphere_total_by_receiver_tower_m;
            reportData.truth_atmosphere_residual_mean_m = ...
                mean(reportData.atmosphere_truth_residual_by_tower_m(:), ...
                'omitnan');

            reportData.truth_atmosphere_residual_std_m = ...
                std(reportData.atmosphere_truth_residual_by_tower_m(:), ...
                0, ...
                'omitnan');

            reportData.truth_atmosphere_residual_rms_m = ...
                sqrt(mean( ...
                reportData.atmosphere_truth_residual_by_tower_m(:).^2, ...
                'omitnan'));

            reportData.truth_atmosphere_residual_max_abs_m = ...
                max(abs(reportData.atmosphere_truth_residual_by_tower_m(:)), ...
                [], ...
                'omitnan');

            reportData.truth_troposphere_residual_mean_m = ...
                mean(reportData.atmosphere_truth_troposphere_residual_by_tower_m(:), ...
                'omitnan');

            reportData.truth_troposphere_residual_std_m = ...
                std(reportData.atmosphere_truth_troposphere_residual_by_tower_m(:), ...
                0, ...
                'omitnan');

            reportData.truth_troposphere_residual_rms_m = ...
                sqrt(mean( ...
                reportData.atmosphere_truth_troposphere_residual_by_tower_m(:).^2, ...
                'omitnan'));

            reportData.truth_troposphere_residual_max_abs_m = ...
                max(abs(reportData.atmosphere_truth_troposphere_residual_by_tower_m(:)), ...
                [], ...
                'omitnan');

            reportData.truth_ionosphere_residual_mean_m = ...
                mean(reportData.atmosphere_truth_ionosphere_residual_by_tower_m(:), ...
                'omitnan');

            reportData.truth_ionosphere_residual_std_m = ...
                std(reportData.atmosphere_truth_ionosphere_residual_by_tower_m(:), ...
                0, ...
                'omitnan');

            reportData.truth_ionosphere_residual_rms_m = ...
                sqrt(mean( ...
                reportData.atmosphere_truth_ionosphere_residual_by_tower_m(:).^2, ...
                'omitnan'));

            reportData.truth_ionosphere_residual_max_abs_m = ...
                max(abs(reportData.atmosphere_truth_ionosphere_residual_by_tower_m(:)), ...
                [], ...
                'omitnan');

            reportData.truth_troposphere_residual_config_sigma_m = ...
                double(sim.truthAtmosphere.residualTroposphereSigma_m) * ...
                double(sim.truthAtmosphere.enableTroposphere);

            reportData.truth_ionosphere_residual_config_sigma_m = ...
                double(sim.truthAtmosphere.residualIonosphereSigma_m) * ...
                double(sim.truthAtmosphere.enableIonosphere);

            reportData.truth_total_residual_config_sigma_m = hypot( ...
                reportData.truth_troposphere_residual_config_sigma_m, ...
                reportData.truth_ionosphere_residual_config_sigma_m);
            reportData.atmosphere_model_delay_by_receiver_tower_m = ...
                sim.history.atmosphere_model_delay_by_receiver_tower_m;
            reportData.atmosphere_model_troposphere_by_receiver_tower_m = ...
                sim.history.atmosphere_model_troposphere_by_receiver_tower_m;
            reportData.atmosphere_model_ionosphere_by_receiver_tower_m = ...
                sim.history.atmosphere_model_ionosphere_by_receiver_tower_m;
            reportData.atmosphere_model_ionosphere_ipp_lat_deg_by_receiver_tower = ...
                sim.history.atmosphere_model_ionosphere_ipp_lat_deg_by_receiver_tower;
            reportData.atmosphere_model_ionosphere_ipp_lon_deg_by_receiver_tower = ...
                sim.history.atmosphere_model_ionosphere_ipp_lon_deg_by_receiver_tower;
            reportData.atmosphere_model_ionosphere_vtec_TECU_by_receiver_tower = ...
                sim.history.atmosphere_model_ionosphere_vtec_TECU_by_receiver_tower;
            reportData.atmosphere_model_ionosphere_stec_TECU_by_receiver_tower = ...
                sim.history.atmosphere_model_ionosphere_stec_TECU_by_receiver_tower;
            reportData.atmosphere_model_ionosphere_mapping_factor_by_receiver_tower = ...
                sim.history.atmosphere_model_ionosphere_mapping_factor_by_receiver_tower;

            reportData.atmosphere_model_ionosphere_frequency_Hz_by_receiver_tower = ...
                sim.history.atmosphere_model_ionosphere_frequency_Hz_by_receiver_tower;
            reportData.atmosphere_model_troposphere_pressure_hPa_by_receiver_tower = ...
                sim.history.atmosphere_model_troposphere_pressure_hPa_by_receiver_tower;

            reportData.atmosphere_model_troposphere_temperature_K_by_receiver_tower = ...
                sim.history.atmosphere_model_troposphere_temperature_K_by_receiver_tower;

            reportData.atmosphere_model_troposphere_relative_humidity_fraction_by_receiver_tower = ...
                sim.history.atmosphere_model_troposphere_relative_humidity_fraction_by_receiver_tower;

            reportData.atmosphere_model_troposphere_water_vapor_pressure_hPa_by_receiver_tower = ...
                sim.history.atmosphere_model_troposphere_water_vapor_pressure_hPa_by_receiver_tower;

            reportData.atmosphere_model_troposphere_zhd_m_by_receiver_tower = ...
                sim.history.atmosphere_model_troposphere_zhd_m_by_receiver_tower;

            reportData.atmosphere_model_troposphere_zwd_m_by_receiver_tower = ...
                sim.history.atmosphere_model_troposphere_zwd_m_by_receiver_tower;

            reportData.atmosphere_model_troposphere_mapping_hydrostatic_by_receiver_tower = ...
                sim.history.atmosphere_model_troposphere_mapping_hydrostatic_by_receiver_tower;

            reportData.atmosphere_model_troposphere_mapping_wet_by_receiver_tower = ...
                sim.history.atmosphere_model_troposphere_mapping_wet_by_receiver_tower;

            reportData.atmosphere_model_troposphere_slant_hydrostatic_m_by_receiver_tower = ...
                sim.history.atmosphere_model_troposphere_slant_hydrostatic_m_by_receiver_tower;

            reportData.atmosphere_model_troposphere_slant_wet_m_by_receiver_tower = ...
                sim.history.atmosphere_model_troposphere_slant_wet_m_by_receiver_tower;
            reportData.atmosphere_residual_by_receiver_tower_m = ...
                sim.history.atmosphere.residual.total_m;
            reportData.atmosphere_troposphere_residual_by_receiver_tower_m = ...
                sim.history.atmosphere.residual.troposphere_m;

            reportData.atmosphere_ionosphere_residual_by_receiver_tower_m = ...
                sim.history.atmosphere.residual.ionosphere_m;
            reportData.mean_truth_atmosphere_delay_m = mean( ...
                sim.history.atmosphere_truth_total_by_receiver_tower_m(:), ...
                'omitnan');

            reportData.mean_model_atmosphere_delay_m = mean( ...
                sim.history.atmosphere_model_delay_by_receiver_tower_m(:), ...
                'omitnan');

            reportData.mean_atmosphere_model_residual_m = mean( ...
                reportData.atmosphere_residual_by_receiver_tower_m(:), ...
                'omitnan');

            reportData.model_atmosphere_residual_sigma_m = ...
                sim.measurementModel.modelAtmosphere.residualCodeSigma_m();

            reportData.truth_atmosphere_residual_sigma_m = ...
                sim.measurementModel.truthAtmosphere.residualCodeSigma_m();

            reportData.mean_deterministic_atmosphere_model_residual_m = ...
                mean(sim.history.atmosphere.residual.deterministic_total_m(:), ...
                'omitnan');

            reportData.model_atmosphere_residual_variance_m2 = ...
                mean(sim.history.atmosphere.covariance.totalVariance_m2(:), ...
                'omitnan');

            reportData.model_atmosphere_covariance_structure = ...
                string(sim.history.atmosphere.covariance.correlation_model);
            reportData.atmosphere_summary_table = ...
                ReportDataBuilder.buildAtmosphereSummaryTable(sim, reportData);
            reportData.stochastic_truth_residual_summary_table = ...
                ReportDataBuilder.buildStochasticTruthResidualSummaryTable( ...
                reportData);
            reportData.ionosphere_map_summary_table = ...
                ReportDataBuilder.buildIonosphereMapSummaryTable(sim, reportData);
            reportData.troposphere_profile_summary_table = ...
                ReportDataBuilder.buildTroposphereProfileSummaryTable(sim, reportData);
            reportData.los_unit_eci_by_receiver_tower = ...
                sim.history.los_unit_eci_by_receiver_tower;
            reportData.pseudorange_error_by_receiver_tower_m = ...
                sim.history.pseudorange_by_receiver_tower_m - ...
                sim.history.true_range_by_receiver_tower_m;

            reportData.receiver_offset_body_by_receiver_m = sim.receiverOffsetsBody_m;
            reportData.covariance_condition_number = sim.history.covariance_condition_number;
            reportData.innovation_condition_number = sim.history.innovation_condition_number;

            reportData.visible_tower_count = sim.history.visible_tower_count;
            reportData.used_tower_count = sim.history.visible_tower_count;
            reportData.measurementNoiseEnabled = sim.measurementModel.measurementNoiseEnabled();
            reportData.numerical_measurement_sigma_floor_m = ...
                sim.measurementModel.effectiveNumericalMeasurementSigma_m();
            reportData.enableElevationMask = sim.measurementModel.elevationMaskEnabled();
            reportData.elevationMask_deg = sim.measurementModel.elevationMaskDeg();

            if GroundTimingNetwork.towerClockEkfEnabled(sim.cfg)
                reportData.clockGaugeMode = "towerClockEKF_meanGroundClockGauge";
                reportData.referenceTowerName = "Mean ground-network clock";
                reportData.clock_estimation_mode = 'spacecraftReceiverClockPlusTowerClockEKF';
            else
                if GroundTimingNetwork.groundClockCorrectionEnabled(sim.cfg)
                    reportData.clockGaugeMode = "externalTowerCorrections";
                    reportData.referenceTowerName = "External ground timing product";
                else
                    reportData.clockGaugeMode = "groundClockResidualsGeneratedButNotEstimated";
