classdef OwnerLocalEstimatorEndpointProvider
    % OwnerLocalEstimatorEndpointProvider  Owner-side revgnss.CommunicationEndpointStateProvider.
    %
    % Reads a local ReverseGNSSSimulation's own ekf/stateMap directly, exactly as
    % revgnss.EndpointStateProduct.fromLocalEstimator does. Never calls
    % TwoWayISLMeasurementBuilder.estimateEndpoint_/truthEndpoint_. Never indexes
    % stateMap.asset beyond the chief (index 1) block and never requires
    % multiAsset.mode='joint'.
    %
    % IMPORTANT (verified against +filter/ReverseGNSSEKF.m): stateMap.asset exists on EVERY
    % EKF -- single-asset, fast, per-asset leaf, and joint -- because buildStateMap_ builds it
    % unconditionally. isfield(stateMap,'asset') is therefore always true and cannot be used
    % to detect a joint state map. The discriminator used below is WIDTH: ekf.nSecondaryAssets
    % > 0, or numel(stateMap.asset) > 1 (both checked independently so a future change to
    % either alone cannot silently open the joint path).
    %
    % The constructed object discards the simulation handle entirely: only the frozen
    % CommunicationEndpointState is retained. This class holds no handle to
    % ReverseGNSSSimulation, SpaceAsset, or any clock object, so it is structurally unable to
    % read truth later, not merely forbidden to.

    properties (SetAccess = immutable)
        endpointIdentifier (1,:) char
        canonicalPhysicalAssetIndex (1,1) double
        declaredEvaluationPolicy (1,:) char
        frozenEpoch_s (1,1) double
        frozenState (1,1)
    end

    methods (Access = private)
        function obj = OwnerLocalEstimatorEndpointProvider(endpointIdentifier, ...
                canonicalPhysicalAssetIndex, declaredEvaluationPolicy, frozenEpoch_s, frozenState)
            if ~isa(frozenState,'revgnss.CommunicationEndpointState')
                error('OwnerLocalEstimatorEndpointProvider:frozenStateType', ...
                    'frozenState must be a revgnss.CommunicationEndpointState.');
            end
            obj.endpointIdentifier = endpointIdentifier;
            obj.canonicalPhysicalAssetIndex = canonicalPhysicalAssetIndex;
            obj.declaredEvaluationPolicy = declaredEvaluationPolicy;
            obj.frozenEpoch_s = frozenEpoch_s;
            obj.frozenState = frozenState;
        end
    end

    methods
        function state = stateAtCoordinateEpoch(obj, coordinateEpoch_s)
            if ~(isnumeric(coordinateEpoch_s) && isscalar(coordinateEpoch_s) && ...
                    isfinite(coordinateEpoch_s) && coordinateEpoch_s == obj.frozenEpoch_s)
                error('OwnerLocalEstimatorEndpointProvider:epochOutsideFrozenScope', ...
                    'This provider is frozen at one coordinate epoch only.');
            end
            state = obj.frozenState;
        end
    end

    methods (Static)
        function provider = fromLocalSimulation(sim, canonicalPhysicalAssetIndex, ...
                coordinateEpoch_s, terminalGeometry)
            if nargin < 4 || isempty(terminalGeometry)
                terminalGeometry = revgnss.OwnerLocalEstimatorEndpointProvider.undeclaredTerminalGeometry_();
            end
            if ~(isa(sim,'revgnss.ReverseGNSSSimulation') && sim.isInit)
                error('OwnerLocalEstimatorEndpointProvider:simulation', ...
                    'An initialized local ReverseGNSSSimulation is required.');
            end
            if sim.lastEstimatedEpoch < 1 || sim.lastTruthEpoch ~= sim.lastEstimatedEpoch
                error('OwnerLocalEstimatorEndpointProvider:localUpdate', ...
                    'An owner-provider state requires a completed local update at its source epoch.');
            end
            expectedEpoch_s = sim.tVec(sim.lastEstimatedEpoch);
            if ~(isnumeric(coordinateEpoch_s) && isscalar(coordinateEpoch_s) && ...
                    isfinite(coordinateEpoch_s) && coordinateEpoch_s == expectedEpoch_s)
                error('OwnerLocalEstimatorEndpointProvider:sourceEpoch', ...
                    'coordinateEpoch_s must equal the most recently completed local-update epoch.');
            end

            % Source-identity guard (retained from Stage 1, EndpointStateProduct:sourceAsset):
            % canonicalPhysicalAssetIndex must identify the local estimator that actually
            % produced the state. CanonicalEndpointIdentity.requireReconciled (used later by
            % LinkObservationDelivery) can only prove two LABELS agree; it cannot inspect which
            % filter produced a state. That property must be established at its source, here.
            expectedAssetIndex = 1;
            if isfield(sim.cfg,'asset') && isfield(sim.cfg.asset,'physicalAssetIndex')
                expectedAssetIndex = sim.cfg.asset.physicalAssetIndex;
            end
            if canonicalPhysicalAssetIndex ~= expectedAssetIndex
                error('OwnerLocalEstimatorEndpointProvider:sourceAsset', ...
                    ['canonicalPhysicalAssetIndex must identify the local estimator that ' ...
                    'produced the state (cfg.asset.physicalAssetIndex).']);
            end

            % Joint refusal: two independent discriminators, both must be false.
            sm = sim.ekf.stateMap;
            isJointStateMap = (sim.ekf.nSecondaryAssets > 0) || ...
                (isfield(sm,'asset') && numel(sm.asset) > 1);
            if isJointStateMap
                error('OwnerLocalEstimatorEndpointProvider:jointStateMapRejected', ...
                    ['This local estimator carries a joint (multi-asset) state map. An owner ' ...
                    'provider must read exactly one independent local filter; it must never ' ...
                    'index a joint-mode secondary-asset block.']);
            end

            blk = revgnss.AssetStateBlock.forAsset(sm,1);
            xMeasurement = sim.ekf.getMeasurementState();
            stateIndices = [blk.r(:);blk.v(:);blk.euler(:);sm.omega_idx(:);blk.b;blk.bdot];
            x = xMeasurement(stateIndices);
            P = sim.ekf.P(stateIndices,stateIndices);

            attitudeErrorCoordinateConvention = 'eulerZYXError_rad';
            covarianceLabels = ...
                revgnss.DistributedLinkProtocolContract.StateSchemaV1CovarianceComponentOrderEuler;
            if strcmp(sim.ekf.attitudeParameterization,'quaternionErrorState')
                covarianceLabels = ...
                    revgnss.DistributedLinkProtocolContract.StateSchemaV1CovarianceComponentOrderTangent;
                attitudeErrorCoordinateConvention = 'rightMultiplicativeLocalTangent_rad';
            end

            productProvenance = struct( ...
                'sourceKind','ownerLocalEstimator', ...
                'productIdentifier','', ...
                'sequenceIdentifier','', ...
                'sourceEpoch_s',coordinateEpoch_s, ...
                'deliveryEpoch_s',coordinateEpoch_s, ...
                'productAge_s',0, ...
                'dynamicsMode',revgnss.OwnerLocalEstimatorEndpointProvider.field_( ...
                    sim.cfg,{'estimator','dynamics','mode'},'unspecified'), ...
                'clockModel',revgnss.OwnerLocalEstimatorEndpointProvider.field_( ...
                    sim.cfg,{'asset','clock','name'},'unspecified'), ...
                'timeStep_s',sim.cfg.simulation.dt_s);

            endpointIdentifier = sprintf('spacecraft:%d',canonicalPhysicalAssetIndex);
            clockAnchorDeclaration = revgnss.EndpointClockAnchorDeclaration.fromLocalEstimatorConfig( ...
                sim.cfg,endpointIdentifier,canonicalPhysicalAssetIndex);
            stateRecord = struct( ...
                'endpointIdentifier',endpointIdentifier, ...
                'canonicalPhysicalAssetIndex',canonicalPhysicalAssetIndex, ...
                'stateSource','estimatorState', ...
                'stateOrigin','ownerLocalEstimator', ...
                'coordinateEpoch_s',coordinateEpoch_s, ...
                'stateEvaluationPolicy','frozenSameEpochOnly', ...
                'coordinateTimeScale',revgnss.DistributedLinkProtocolContract.CoordinateTimeScale, ...
                'frameIdentifier',revgnss.DistributedLinkProtocolContract.FrameIdentifier, ...
                'clockDatumIdentifier',revgnss.DistributedLinkProtocolContract.ClockDatumIdentifier, ...
                'stateSchemaVersion',revgnss.DistributedLinkProtocolContract.StateSchemaVersion, ...
                'attitudeErrorCoordinateConvention',attitudeErrorCoordinateConvention, ...
                'stateComponentOrder', ...
                    {revgnss.DistributedLinkProtocolContract.StateSchemaV1StateComponentOrder}, ...
                'covarianceComponentOrder',{covarianceLabels}, ...
                'stateVector',x, ...
                'covarianceBlock',P, ...
                'positionEcef_m',x(1:3), ...
                'velocityEcef_mps',x(4:6), ...
                'attitudeEulerZyx_rad',sim.ekf.getReportEulerRad(), ...
                'angularRateBody_radps',x(10:12), ...
                'clockBias_m',x(13), ...
                'clockDriftRate_mps',x(14), ...
                'terminalGeometry',terminalGeometry, ...
                'productProvenance',productProvenance, ...
                'qualityFlags',struct('estimatorDerived',true,'truthUsed',false, ...
                    'diagnosticOnly',false,'estimatorEligible',true), ...
                'clockAnchorDeclaration',clockAnchorDeclaration);
            frozenState = revgnss.CommunicationEndpointState(stateRecord);

            provider = revgnss.OwnerLocalEstimatorEndpointProvider(endpointIdentifier, ...
                canonicalPhysicalAssetIndex,'frozenSameEpochOnly',coordinateEpoch_s,frozenState);
        end
    end

    methods (Static, Access = private)
        function geometry = undeclaredTerminalGeometry_()
            geometry = struct('declared',false, ...
                'transmitTerminalIdentifier','terminal:undeclared', ...
                'receiveTerminalIdentifier','terminal:undeclared', ...
                'transmitAntennaIdentifier','antenna:undeclared', ...
                'receiveAntennaIdentifier','antenna:undeclared', ...
                'transmitPhaseCentreOffset_body_m',zeros(3,1), ...
                'receivePhaseCentreOffset_body_m',zeros(3,1));
        end

        function value = field_(s,path,defaultValue)
            value = s;
            for index = 1:numel(path)
                if ~isstruct(value) || ~isfield(value,path{index})
                    value = defaultValue;
                    return
                end
                value = value.(path{index});
            end
            if isstring(value); value = char(value); end
        end
    end
end
