            end
        end

        function requireSanctionedIslConfiguration_(cfg)
            % requireSanctionedIslConfiguration_  Additional gates reachable ONLY under the
            % sanctioned coherentTwoWayCodeRange tuple (plan Section 2.3.1 G4-G8-family):
            % the two-way link must be enabled with useInEKF=false, every persistent
            % calibration/plasma error source must be identically zero (invariant 8 -- these
            % are never modelled as a distributed-adapter state, so a nonzero value would leak
            % into R as white per-epoch noise), and no two enabled links may share the same
            % initiator (a second same-epoch delivery to one owner would linearize at a stale
            % pre-update prior; revgnss.OwnerLocalEstimatorEndpointProvider is frozen at
            % construction and cannot see an update applied earlier in the same epoch).
            if ~revgnss.IndependentFleetCoordinator.logicalPath_( ...
                    cfg,{'measurements','isl','twoWay','enable'},false) || ...
                    ~revgnss.IndependentFleetCoordinator.logicalPath_( ...
                    cfg,{'measurements','isl','twoWay','range','enable'},false)
                error('IndependentFleetCoordinator:twoWayRangeNotEnabled', ...
                    'The sanctioned tuple requires measurements.isl.twoWay.enable and .range.enable both true.');
            end
            requireZero_ = @(path,identifierSuffix) revgnss.IndependentFleetCoordinator. ...
                requireZeroPath_(cfg,path,identifierSuffix);
            requireZero_({'measurements','isl','twoWay','truth','turnaroundCalibrationError_s'}, ...
                'persistentCalibrationUnavailableForDistributedRow');
            requireZero_({'measurements','isl','twoWay','truth','terminalCalibrationError_s'}, ...
                'persistentCalibrationUnavailableForDistributedRow');
            requireZero_({'measurements','isl','twoWay','calibration','turnaroundSigma_s'}, ...
                'persistentCalibrationUnavailableForDistributedRow');
            requireZero_({'measurements','isl','twoWay','calibration','terminalSigma_s'}, ...
                'persistentCalibrationUnavailableForDistributedRow');
            if revgnss.IndependentFleetCoordinator.logicalPath_( ...
                    cfg,{'measurements','isl','twoWay','calibration','residualBiasState','enable'},false)
                error('IndependentFleetCoordinator:persistentCalibrationUnavailableForDistributedRow', ...
                    'measurements.isl.twoWay.calibration.residualBiasState.enable must be false.');
            end
            requireZero_({'measurements','isl','twoWay','range','plasma','residualSigma_m'}, ...
                'plasmaGroupDelayUnavailableForDistributedRow');
            if revgnss.IndependentFleetCoordinator.logicalPath_( ...
                    cfg,{'measurements','isl','twoWay','range','plasma','enable'},false)
                error('IndependentFleetCoordinator:plasmaGroupDelayUnavailableForDistributedRow', ...
                    'measurements.isl.twoWay.range.plasma.enable must be false.');
            end

            links = revgnss.TwoWayISLMeasurementBuilder.linkDefinitions(cfg);
            for linkIndex = 1:numel(links)
                link = links(linkIndex);
                if isfield(link,'turnaroundCalibrationError_s') && ...
                        isnumeric(link.turnaroundCalibrationError_s) && ...
                        link.turnaroundCalibrationError_s ~= 0
                    error('IndependentFleetCoordinator:persistentCalibrationUnavailableForDistributedRow', ...
                        'Link %d declares a nonzero turnaroundCalibrationError_s.',linkIndex);
                end
                if isfield(link,'terminalCalibrationError_s') && ...
                        isnumeric(link.terminalCalibrationError_s) && ...
                        link.terminalCalibrationError_s ~= 0
                    error('IndependentFleetCoordinator:persistentCalibrationUnavailableForDistributedRow', ...
                        'Link %d declares a nonzero terminalCalibrationError_s.',linkIndex);
                end
            end
            if ~isempty(links)
                initiatorIndices = [links.initiatorAssetIndex];
                if numel(unique(initiatorIndices)) ~= numel(initiatorIndices)
                    error('IndependentFleetCoordinator:coFiringLinksPerOwner', ...
                        ['No two enabled links may share the same initiatorAssetIndex: a second ' ...
                        'same-epoch delivery to one owner cannot see the first delivery''s update.']);
                end
            end
        end

        function requireZeroPath_(cfg,path,identifierSuffix)
            value = revgnss.IndependentFleetCoordinator.numericPath_(cfg,path,0);
            if value ~= 0
                error(['IndependentFleetCoordinator:' identifierSuffix], ...
                    '%s must be exactly zero under the sanctioned linkUpdate tuple.', ...
                    strjoin(path,'.'));
            end
        end
