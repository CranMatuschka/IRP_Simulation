        function tf = islObservableRequested_(cfg,sanctionedActive)
            % islObservableRequested_  measurements.isl.enable/.twoWay.enable/.twoWay.range.enable
            % are the three paths the sanctioned coherentTwoWayCodeRange tuple legitimately
            % needs (plan Section 2.3.1 / audit A17: measurements.isl.enable is the two-way
