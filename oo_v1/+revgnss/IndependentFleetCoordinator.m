                {'multiAsset','twoWayISL','enable'}, ...
                {'multiAsset','twoWayTimeTransferISL','enable'}, ...
                {'multiAsset','twoWayTimeTransferISL','useInEKF'}};
            tf = false;
            for index = 1:numel(paths)
                if revgnss.IndependentFleetCoordinator.logicalPath_(cfg,paths{index},false)
                    tf = true;
