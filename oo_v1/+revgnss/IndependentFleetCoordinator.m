            % gate) -- exempted from this list ONLY when sanctionedActive, and checked
            % separately by the caller otherwise. Every leaf still forces measurements.isl.enable
            % (and every other measurements.isl.* key) false regardless of this fleet-level
            % value (IndependentFleetScenarioFactory), so this can never reach a per-asset-leaf
            % EKF; range.useInEKF is checked unconditionally by the caller, not here.
            if nargin < 2; sanctionedActive = false; end
            paths = { ...
                {'measurements','isl','code','enable'}, ...
                {'measurements','isl','code','useInEKF'}, ...
                {'measurements','isl','doppler','enable'}, ...
                {'measurements','isl','doppler','useInEKF'}, ...
