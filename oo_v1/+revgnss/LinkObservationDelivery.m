classdef LinkObservationDelivery
    % LinkObservationDelivery  Interface #2 (plan Section 2.1): binds one immutable physical
    % observation to canonical endpoints, one owner filter, source/delivery epochs, a frozen
    % estimator-eligible remote product identifier, and covariance/calibration groups.
    %
    % This class performs NO strcmp-based endpoint-identifier translation anywhere: every
    % endpoint binding goes through revgnss.CanonicalEndpointIdentity.requireReconciled. It
    % proves the two LABELS agree; it relies on revgnss.OwnerLocalEstimatorEndpointProvider
    % having already proven, at its own construction, that the label names the filter that
    % actually produced the state (see that class's sourceAsset guard).
    %
    % The lifecycle (eligible/consumed/rejected) itself is NOT owned here: it belongs to
    % revgnss.DistributedDeliveryLedger. This class only proposes one candidate binding.

    properties (Constant)
        AllowedPhysicalRecordClasses = { ...
            'revgnss.InterSatelliteObservationRecord', ...
            'revgnss.InterSatelliteTimeTransferObservationRecord'};
        AllowedOwnerPolicies = {'disabled','initiator'};
        AllowedRoleReversalPolicies = {'disabled','separateScheduledSession'};
        AllowedRemoteProductPropagationPolicies = {'frozenSameEpochOnly'};
        % remoteProductSchemaMismatch is reserved vocabulary: schema-version mismatches
        % (DistributedLinkProtocolContract:stateComponentOrder /
        % :covarianceComponentOrder) are raised while BUILDING a FrozenProductEndpointProvider
        % (requireDeliveryProvenance runs inside fromEstimatorEligibleProduct), before propose()
        % ever receives the already-constructed provider, so this code has no reachable
        % identifier today. Kept frozen for a future propose()-time schema check.
        AllowedRejectionReasonCodes = { ...
            'endpointIdentityUnreconciled','remoteProductStale','remoteProductNotYetDelivered', ...
            'remoteProductNotEstimatorEligible','remoteProductSchemaMismatch', ...
            'attitudeConventionMismatch','covarianceGroupNotSingleton','calibrationProvenanceMissing', ...
            'calibrationValidityExpired','calibrationOwnerUndeclared','ownerPolicyUnsupported', ...
            'ownerPolicyNotDefinedForRecordType','roleReversalUnsupported','recordUnavailable', ...
            'recordClassNotSanctioned','outOfSequenceDelivery','productAgeNonZero', ...
            'propagationPolicyUnsupported','endpointsNotDistinct','sameEpochScopeViolated', ...
            'ownerProviderSourceAssetMismatch','commonSourceNotRejected', ...
            'correlationPolicyUnsupported','providerClassNotSanctioned', ...
            'observableNotSelectable','recordClassNotSupportedForObservable', ...
            'persistentCalibrationTreatmentUnsupported', ...
            'observableClockClaimUndeclared','clockDatumMismatch', ...
            'clockAnchorUndeclared','unanchoredClockPair','propagationDelayInvalid', ...
            'remoteStateProvenanceUnsupported'};
    end

