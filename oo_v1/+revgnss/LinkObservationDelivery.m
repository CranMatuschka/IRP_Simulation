    methods (Static, Access = private)
        function [ownerField,remoteField] = ownerEndpointFieldFor_(recordClass, ownerPolicy)
            if strcmp(recordClass,'revgnss.InterSatelliteObservationRecord') && ...
                    strcmp(ownerPolicy,'initiator')
                ownerField = 'initiatorAssetIdentifier';
                remoteField = 'transponderAssetIdentifier';
                return
            end
            error('LinkObservationDelivery:ownerPolicyNotDefinedForRecordType', ...
                ['ownerPolicy ''%s'' has no defined owner/remote endpoint role for record ' ...
                'class %s.'],ownerPolicy,recordClass);
        end
