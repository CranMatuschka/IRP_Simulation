        function v = getf_(cfg, dotPath)
            % Safe nested field accessor. dotPath: 'a.b.c' (no leading 'cfg.').
            try
                v = cfg;
                parts = strsplit(dotPath, '.');
                if strcmp(parts{1},'cfg'); parts = parts(2:end); end
                for k = 1:numel(parts)
                    v = v.(parts{k});
                end
            catch
                v = [];
            end
        end

        function s = fmtVal_(v)
            % Format MATLAB value as compact string.
            if isempty(v)
                s = 'N/A';
            elseif islogical(v) && isscalar(v)
                if v; s = 'true'; else; s = 'false'; end
            elseif islogical(v)
                p = arrayfun(@(x) num2str(double(x)), v, 'UniformOutput', false);
                s = ['[' strjoin(p,',') ']'];
            elseif isnumeric(v) && isscalar(v)
                if isnan(v)
                    s = 'NaN';
                elseif v == round(v) && abs(v) < 1e9
                    s = sprintf('%g', v);
                else
                    s = sprintf('%.4g', v);
                end
            elseif isnumeric(v) && numel(v) <= 8
                s = mat2str(v, 4);
            elseif isnumeric(v)
                s = sprintf('[%dx%d %s]', size(v,1), size(v,2), class(v));
            elseif ischar(v)
                s = v;
            elseif iscell(v) && all(cellfun(@ischar, v))
                s = ['{' strjoin(v,',') '}'];
            else
                s = class(v);
            end
        end

