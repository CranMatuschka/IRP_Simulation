% ---- File-scope helpers (not classdef methods) --------------------------

function b = logical_G_(v)
    % Cast safely to logical; missing → false.
    if isempty(v); b = false;
    elseif islogical(v) && isscalar(v); b = v;
    elseif isnumeric(v) && isscalar(v); b = logical(v);
    else; b = false;
    end
end

function s = ternst_(cond, a, b)
    % Ternary for status strings.
    if cond; s = a; else; s = b; end
end

function n = numel_safe_(cfg, field)
    try; n = numel(cfg.(field)); catch; n = 0; end
end

function v = safe_num_(val, default)
    if isnumeric(val) && isscalar(val) && ~isnan(val); v = val; else; v = default; end
end

function v = scalar0_(val)
    if isnumeric(val) && isscalar(val) && isfinite(val); v = double(val); else; v = 0; end
end
