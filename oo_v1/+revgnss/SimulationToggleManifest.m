classdef SimulationToggleManifest
    % SimulationToggleManifest  Simulation-impacting toggle manifest from cfg.
    %
    % Usage:
    %   manifest = revgnss.SimulationToggleManifest.fromConfig(cfg);          % cfg only
    %   manifest = revgnss.SimulationToggleManifest.fromConfig(cfg, out);     % cfg + runtime out
    %   T        = revgnss.SimulationToggleManifest.toTable(manifest);
    %   revgnss.SimulationToggleManifest.writeCsv(T, '/path/manifest.csv');
    %   compact  = revgnss.SimulationToggleManifest.compact(manifest);
    %
    % Status values:
    %   active               - implemented and active in this cfg
    %   inactive_available   - implemented but off in this cfg
    %   guarded_or_config_only - present but guarded, unsupported, or irrelevant to active scenario
    %   diagnostic_only      - does not change physics/EKF; changes diagnostics/reporting only

    methods (Static)

        % ----------------------------------------------------------------
        function manifest = fromConfig(cfg, varargin)
            % fromConfig  Build manifest struct array from finalized cfg.
            %   manifest = fromConfig(cfg)       — cfg-based classification only
            %   manifest = fromConfig(cfg, out)  — out.summary used for runtime status
            % The 'out' struct (optional) is currently unused beyond validation; the
            % manifest is fully determined by cfg at this time.
            G  = @(p) revgnss.SimulationToggleManifest.getf_(cfg, p);
            FV = @(v) revgnss.SimulationToggleManifest.fmtVal_(v);
            MK = @(cat,path,val,st,si,aff,cond,notes) ...
                 revgnss.SimulationToggleManifest.mkRow_(cat, path, FV(val), st, si, aff, cond, notes);
            A  = 'active';
            IA = 'inactive_available';
            GC = 'guarded_or_config_only';
            DO = 'diagnostic_only';
            rows = {};

            %% --- Signals -----------------------------------------------
            mask  = G('signals.enabledMask');
            if isempty(mask); mask = true; end
            isDual = numel(mask) >= 2 && mask(1) && mask(2);
            names_ = G('signals.names');
            freqs_ = G('signals.frequencyHz');
            ebfC_  = G('measurements.code.enabledByFrequency');
            ebfCar_= G('measurements.carrier.enabledByFrequency');

            if isDual; stMask = A; else; stMask = IA; end
            rows{end+1} = MK('Signals','cfg.signals.enabledMask', mask, stMask, true, ...
                'measurementRows,measurementValue,R,stateDimension', 'always', ...
                'L1 only: single-freq code/carrier/Doppler; L1+L2: enables IF rows and baseline attitude AR');

            if isempty(names_); names_ = {'L1'}; end
            rows{end+1} = MK('Signals','cfg.signals.names', names_, A, true, ...
                'measurementRows', 'derived by finalizeConfig', ...
                'Signal catalogue; ordering must match enabledMask and frequencyHz');

            if ~isempty(freqs_)
                rows{end+1} = MK('Signals','cfg.signals.frequencyHz', freqs_, A, true, ...
                    'measurementValue,R', 'derived by finalizeConfig', ...
                    'Carrier frequency determines wavelength and IF combination coefficients');
            end

            wl_ = G('signals.wavelength_m');
            if isempty(wl_)
                try
                    c_ = 299792458;
                    if ~isempty(freqs_) && isnumeric(freqs_)
                        wl_ = c_ ./ freqs_;
                    end
                catch; end
            end
            if ~isempty(wl_)
                rows{end+1} = MK('Signals','cfg.signals.wavelength_m (derived)', wl_, A, true, ...
                    'measurementValue', 'derived from frequencyHz', ...
                    'Wavelength controls carrier phase conversion cycles→metres');
            end

            if isDual; stDual = A; else; stDual = IA; end
            rows{end+1} = MK('Signals','derived: dualFrequency mode', isDual, stDual, true, ...
                'measurementRows,R,stateDimension', 'enabledMask=[true,true]', ...
                'Dual-freq enables IF combination rows; single-freq blocks them');

            if ~isempty(ebfC_)
                rows{end+1} = MK('Signals','cfg.measurements.code.enabledByFrequency', ebfC_, A, true, ...
                    'measurementRows', 'derived by finalizeConfig from enabledMask', ...
                    'Per-frequency code row inclusion; must match enabledMask');
            end
            if ~isempty(ebfCar_)
                rows{end+1} = MK('Signals','cfg.measurements.carrier.enabledByFrequency', ebfCar_, ...
                    ternst_(isDual && logical(G('measurements.carrierPhase.enable')), A, IA), true, ...
                    'measurementRows', 'derived by finalizeConfig from enabledMask', ...
                    'Per-frequency carrier row inclusion; single-freq excludes L2 carrier rows');
            end

            %% --- Scenario / topology -----------------------------------
            nSA_ = G('scenario.nSpaceAssets'); if isempty(nSA_); nSA_=1; end
            nRx_ = G('scenario.nReceivers');   if isempty(nRx_); nRx_=1; end
            nTw_ = G('scenario.nTowers');       if isempty(nTw_); nTw_=5; end
            orc_ = G('scenario.orbitClass');    if isempty(orc_); orc_='GEO'; end
            islEn_    = logical_G_(G('measurements.isl.enable'));
            twstftEn_ = logical_G_(G('measurements.twstft.enable'));
            twoWayEn_ = logical_G_(G('measurements.isl.twoWay.enable'));
            groundRelayEn_  = logical_G_(G('measurements.groundRelayTimeTransfer.enable'));
            groundRelayEkf_ = logical_G_(G('measurements.groundRelayTimeTransfer.useInEKF'));
            islTimeTransferEn_ = logical_G_( ...
                G('measurements.isl.twoWay.timeTransfer.enable'));
            islTimeTransferEkf_ = logical_G_( ...
                G('measurements.isl.twoWay.timeTransfer.useInEKF'));
            islTimeTransferMode_ = ...
                G('measurements.isl.twoWay.timeTransfer.mode');
            fleetEnabled_ = logical_G_(G('multiAsset.distributedEstimator.enable'));
            fleetExchange_ = logical_G_( ...
                G('multiAsset.distributedEstimator.stateExchange.enable'));
            fleetMode_ = G('multiAsset.distributedEstimator.executionMode');
            fleetAge_ = G('multiAsset.distributedEstimator.stateExchange.maximumAge_s');
            fleetDelay_ = G('multiAsset.distributedEstimator.stateExchange.deliveryDelay_s');
            fleetLinkUpdate_ = logical_G_( ...
                G('multiAsset.distributedEstimator.linkUpdate.enable'));
            fleetOwner_ = G('multiAsset.distributedEstimator.linkUpdate.ownerPolicy');
            fleetCorrelation_ = G('multiAsset.distributedEstimator.linkUpdate.correlationPolicy');
            fleetTowerClock_ = G( ...
                'multiAsset.distributedEstimator.linkUpdate.commonSourceTreatment.towerClockProduct');
            fleetTerminalCal_ = G( ...
                'multiAsset.distributedEstimator.linkUpdate.commonSourceTreatment.terminalCalibration');
            fleetTransmittedState_ = G( ...
                'multiAsset.distributedEstimator.linkUpdate.commonSourceTreatment.transmittedStateProduct');
            fleetSessionTiming_ = G( ...
                'multiAsset.distributedEstimator.linkUpdate.commonSourceTreatment.sessionTimingProduct');
            fleetSharedForceAtmosphere_ = G( ...
                'multiAsset.distributedEstimator.linkUpdate.commonSourceTreatment.sharedForceAtmosphericProduct');
            fleetClockClaim_ = G( ...
                'multiAsset.distributedEstimator.linkUpdate.timeTransferClockClaim');
            fleetOos_ = G('multiAsset.distributedEstimator.outOfSequencePolicy');
            fleetEligibleProfile_ = logical_G_(G( ...
                'multiAsset.distributedEstimator.stateExchange.estimatorEligibleProfile.enable'));
            fleetDeliveryLedger_ = logical_G_( ...
                G('multiAsset.distributedEstimator.deliveryLedger.enable'));
            fleetPropagation_ = G('multiAsset.distributedEstimator.linkUpdate.remoteProductPropagationPolicy');
            fleetRoleReversal_ = G('multiAsset.distributedEstimator.linkUpdate.roleReversalPolicy');
            fleetCalibrationOwner_ = G( ...
                'multiAsset.distributedEstimator.linkUpdate.calibrationOwnership.policy');
            fleetUpdateObservable_ = G( ...
                'multiAsset.distributedEstimator.linkUpdate.updateAdapter.observable');
            fleetCorrelationNetworkPolicy_ = G('multiAsset.distributedEstimator.correlationNetwork.policy');
            fleetCorrelationNetworkMaxFleetSize_ = G( ...
                'multiAsset.distributedEstimator.correlationNetwork.maximumFleetSize');
            fleetCorrelationNetworkCommonProcessNoiseTreatment_ = G( ...
                'multiAsset.distributedEstimator.correlationNetwork.commonProcessNoiseTreatment');
            fleetCorrelationNetworkAuditEnabled_ = logical_G_( ...
                G('multiAsset.distributedEstimator.correlationNetwork.audit.enable'));
            fleetCorrelationNetworkLinkUpdateRouting_ = G( ...
                'multiAsset.distributedEstimator.correlationNetwork.linkUpdateRouting');
            multiAssetMode_ = G('multiAsset.mode');

            rows{end+1} = MK('Scenario','cfg.scenario.nSpaceAssets', nSA_, A, true, ...
                'stateDimension,measurementRows', 'always', ...
                '1 = one local EKF; >1 selects an explicit joint, report-time federated, or independent-local-EKF architecture');
            rows{end+1} = MK('Scenario','cfg.scenario.nReceivers', nRx_, A, true, ...
                'stateDimension,attitude', 'always', ...
                'nReceivers=1: no attitude; nReceivers>1: enables lever-arm attitude EKF');
            rows{end+1} = MK('Scenario','cfg.scenario.nTowers', nTw_, A, true, ...
                'measurementRows', 'always', ...
                'Number of active ground towers; finalizeConfig trims tower array');
            rows{end+1} = MK('Scenario','cfg.scenario.orbitClass', orc_, A, false, ...
                'truth', 'always (documentary)', ...
                'Orbit class label; dynamics controlled by orbit.truth.mode');

            stMA = ternst_(nSA_ > 1 && (fleetEnabled_ || ...
                strcmpi(char(string(multiAssetMode_)),'joint')),A,GC);
            rows{end+1} = MK('Scenario','derived: multi-asset estimation', nSA_>1, stMA, false, ...
                'stateDimension', 'nSpaceAssets>1', ...
                'Joint mode is centralized; independentLocalEkfsGroundOnly is one local EKF per spacecraft with no Stage-1 ISL update');

            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.enable',fleetEnabled_, ...
                ternst_(fleetEnabled_,A,IA),true,'executionArchitecture', ...
                'nSpaceAssets>1 and multiAsset.mode=''fast''', ...
                'Stage 1: one complete local EKF per spacecraft, synchronized by coordinate epoch');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.executionMode',fleetMode_, ...
                ternst_(fleetEnabled_,A,IA),true,'executionSchedule', ...
                'distributedEstimator.enable=true', ...
                'Only epochSynchronous is implemented; all truth phases precede all local updates');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.stateExchange.enable',fleetExchange_, ...
                ternst_(fleetEnabled_ && fleetExchange_,A,IA),true,'provenance', ...
                'distributedEstimator.enable=true', ...
                'Publishes timestamped local-estimator products only; it never changes another local EKF in Stage 1');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.stateExchange.maximumAge_s',fleetAge_, ...
                ternst_(fleetEnabled_ && fleetExchange_,A,IA),true,'productStatus', ...
                'stateExchange.enable=true', ...
                'Products older than this limit are retained as stale diagnostic provenance, never applied');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.stateExchange.deliveryDelay_s',fleetDelay_, ...
                ternst_(fleetEnabled_ && fleetExchange_,A,IA),true,'productStatus', ...
                'stateExchange.enable=true', ...
                'Coordinate-time delivery delay applied to a local estimator state product');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.enable',fleetLinkUpdate_,GC, ...
                true,'measurementRows,crossSpacecraftCovariance', ...
                'not implemented in Stage 1', ...
                'ISL estimator updates remain disabled until a covariance-aware distributed update exists');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.ownerPolicy',fleetOwner_,GC, ...
                true,'informationOwnership','not implemented in Stage 1', ...
                'Reserved for a future exactly-once link-owner policy');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.correlationPolicy',fleetCorrelation_,GC, ...
                true,'crossSpacecraftCovariance','not implemented in Stage 1', ...
                'Reserved for a future declared common-information/correlation treatment');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.commonSourceTreatment.towerClockProduct', ...
                fleetTowerClock_,GC,true,'crossSpacecraftCovariance', ...
                'not implemented until Section 2.2 delivers a proven treatment', ...
                'Frozen Stage-2 correlation vocabulary (Section 2.0.5); only ''rejected'' validates today');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.commonSourceTreatment.terminalCalibration', ...
                fleetTerminalCal_,GC,true,'crossSpacecraftCovariance', ...
                'not implemented until Section 2.2 delivers a proven treatment', ...
                'Frozen Stage-2 correlation vocabulary (Section 2.0.5); only ''rejected'' validates today');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.commonSourceTreatment.transmittedStateProduct', ...
                fleetTransmittedState_,GC,true,'crossSpacecraftCovariance', ...
                'not implemented until Section 2.2 delivers a proven treatment', ...
                'Frozen Stage-2 correlation vocabulary (Section 2.0.5); only ''rejected'' validates today');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.commonSourceTreatment.sessionTimingProduct', ...
                fleetSessionTiming_,GC,true,'crossSpacecraftCovariance', ...
                'not implemented until Section 2.2 delivers a proven treatment', ...
                'Frozen Stage-2 correlation vocabulary (Section 2.0.5); only ''rejected'' validates today');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.commonSourceTreatment.sharedForceAtmosphericProduct', ...
                fleetSharedForceAtmosphere_,GC,true,'crossSpacecraftCovariance', ...
                'not implemented until Section 2.2 delivers a proven treatment', ...
                'Frozen Stage-2 correlation vocabulary (Section 2.0.5); only ''rejected'' validates today');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.timeTransferClockClaim',fleetClockClaim_,GC, ...
                true,'clockGauge','not implemented in Stage 1', ...
                ['Frozen Stage-2 clock claim (Section 2.0.6): a reciprocal/two-way row ' ...
                'observes a relative bias only, never absolute or drift']);
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.outOfSequencePolicy',fleetOos_, ...
                ternst_(fleetEnabled_,A,IA),true,'productDelivery', ...
                'distributedEstimator.enable=true', ...
                'Stage 1 rejects out-of-sequence state products rather than applying them at an incorrect epoch');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.stateExchange.estimatorEligibleProfile.enable', ...
                fleetEligibleProfile_, ...
                ternst_(fleetEnabled_ && fleetExchange_ && fleetEligibleProfile_,A,IA),true, ...
                'provenance,productDelivery', ...
                ['stateExchange.enable=true and same-epoch scope (maximumAge_s=0, ' ...
                'deliveryDelay_s=0); coordinator config only, forced false on every per-asset leaf'], ...
                ['Section 2.0.4 estimator-eligible publication profile; the Stage-1 diagnostic ' ...
                'product and journal are unchanged and still published']);
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.deliveryLedger.enable',fleetDeliveryLedger_, ...
                ternst_(fleetEnabled_ && fleetDeliveryLedger_,A,IA),true, ...
                'informationOwnership,productDelivery', ...
                'distributedEstimator.enable=true; coordinator config only, forced false on every per-asset leaf', ...
                ['Section 2.1 rule 2 coordinator-owned fleet delivery ledger; zero deliveries exist ' ...
                'until Section 2.3 adds an observable adapter']);
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.remoteProductPropagationPolicy', ...
                fleetPropagation_,GC,true,'crossSpacecraftCovariance,productStatus', ...
                'not implemented beyond frozenSameEpochOnly', ...
                ['Section 2.1 rule 3: only frozenSameEpochOnly validates; a delayed product is ' ...
                'rejected, never silently treated as current']);
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.roleReversalPolicy', ...
                fleetRoleReversal_,GC,true,'informationOwnership', ...
                'not implemented in Section 2.1', ...
                ['Section 2.1 rule 4: ownerPolicy=initiator is the first valid policy; role ' ...
                'reversal needs a separately identified non-overlapping scheduled session']);
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.calibrationOwnership.policy', ...
                fleetCalibrationOwner_,GC,true,'crossSpacecraftCovariance,calibrationOwnership', ...
                'not implemented in Section 2.1', ...
                ['Section 2.1 DistributedLinkCalibrationState single-owner registry; only ' ...
                'undeclared validates, so no persistent calibration can be claimed']);
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.linkUpdate.updateAdapter.observable', ...
                fleetUpdateObservable_,GC,true,'measurementRows', ...
                'no concrete adapter exists (Section 2.3)', ...
                ['DistributedLinkUpdateAdapter is a contract shape only; the registered-adapter ' ...
                'list is empty and every real observable is refused']);

            fleetCorrelationNetworkOn_ = strcmp(char(string(fleetCorrelationNetworkPolicy_)), ...
                'exactPairwiseCrossCovariance');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.correlationNetwork.policy', ...
                fleetCorrelationNetworkPolicy_,ternst_(fleetCorrelationNetworkOn_,A,IA),true, ...
                'crossSpacecraftCovariance', ...
                'distributedEstimator.enable=true, deliveryLedger.enable=true', ...
                ['Stage 3.1: tracks pairwise cross-covariance P_ij only, consuming nothing to move ' ...
                'a state by itself; whether a delivery''s route actually moves a second filter is ' ...
                'the separate linkUpdateRouting toggle below (Section 3.2)']);
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.correlationNetwork.linkUpdateRouting', ...
                fleetCorrelationNetworkLinkUpdateRouting_, ...
                ternst_(fleetCorrelationNetworkOn_ && ...
                    strcmp(char(string(fleetCorrelationNetworkLinkUpdateRouting_)), ...
                    'pairExactWhenBothEndpointsTracked'),A,IA),true, ...
                'crossSpacecraftCovariance', 'correlationNetwork.policy enabled', ...
                ['Section 3.2: ''pairExactWhenBothEndpointsTracked'' applies a synchronized exact ' ...
                'update to BOTH endpoint filters (not just the owner) for coherentTwoWayCodeRange ' ...
                'deliveries where both endpoints are tracked with a fresh cross block; the default ' ...
                '''conservativeBoundOnly'' never routes a delivery differently from Stage 3.1']);
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.correlationNetwork.maximumFleetSize', ...
                fleetCorrelationNetworkMaxFleetSize_,ternst_(fleetCorrelationNetworkOn_,A,IA),true, ...
                'crossSpacecraftCovariance', 'correlationNetwork.policy enabled', ...
                'Hard configured fleet-size limit; exceeding it fails at initialize(), never drops a cross block');
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.correlationNetwork.commonProcessNoiseTreatment', ...
                fleetCorrelationNetworkCommonProcessNoiseTreatment_,GC,true,'crossSpacecraftCovariance', ...
                'refused on the live path (Section 3.3 scope)', ...
                ['declaredCommonAccelerationGroup needs the matching diagonal in each leaf''s own ' ...
                'buildQ_, which Stage 3.1 does not add']);
            rows{end+1} = MK('Fleet execution', ...
                'cfg.multiAsset.distributedEstimator.correlationNetwork.audit.enable', ...
                fleetCorrelationNetworkAuditEnabled_, ...
                ternst_(fleetCorrelationNetworkOn_ && fleetCorrelationNetworkAuditEnabled_,A,IA),false, ...
                'diagnostics', 'correlationNetwork.policy enabled', ...
                'Periodic PSD/symmetry certificate of the transiently-assembled small-fleet covariance');

            rows{end+1} = MK('Scenario','cfg.measurements.isl.enable', islEn_, GC, false, ...
                'measurementRows', 'isl.enable=true', ...
                'ISL one-way: guarded/irrelevant for single-asset one-way scenario');
            rows{end+1} = MK('Scenario','cfg.measurements.twstft.enable', twstftEn_, GC, false, ...
                'measurementRows', 'twstft.enable=true', ...
                'TWSTFT: guarded/irrelevant for single-asset one-way scenario');
            rows{end+1} = MK('Scenario','cfg.measurements.isl.twoWay.enable', twoWayEn_, GC, false, ...
                'measurementRows', 'isl.twoWay.enable=true', ...
                'Two-way ISL: guarded/irrelevant for single-asset one-way scenario');
            rows{end+1} = MK('Scenario', ...
                'cfg.measurements.groundRelayTimeTransfer.enable', groundRelayEn_, GC, false, ...
                'measurementRows', 'groundRelayTimeTransfer.enable=true', ...
                ['Classical relay TWSTFT session processor: report-only this stage, guarded/' ...
                 'irrelevant unless explicitly enabled with a complete station-pair/relay configuration']);
            rows{end+1} = MK('Scenario', ...
                'cfg.measurements.groundRelayTimeTransfer.useInEKF', groundRelayEkf_, GC, false, ...
                'measurementRows', 'always guarded this stage', ...
                ['Hard-refused true this stage: no live coordinator-routed path exists to apply an ' ...
                 'EKF update through (report-only, revgnss.GroundRelayTimeTransferSessionBuilder)']);

            %% --- Crosslink (ISL) carrier phase --------------------------
            islTimeTransferLive_ = islEn_ && twoWayEn_ && ...
                islTimeTransferEn_ && nSA_ > 1;
            rows{end+1} = MK('Crosslink', ...
                'cfg.measurements.isl.twoWay.timeTransfer.enable', ...
                islTimeTransferEn_,ternst_(islTimeTransferLive_,A,IA),true, ...
                'measurementRows,measurementValue,R', ...
                'isl.enable=true, isl.twoWay.enable=true, nSpaceAssets>1', ...
                ['Generates a processed reciprocal clock-difference observation ' ...
                 'between two estimated spacecraft']);
            rows{end+1} = MK('Crosslink', ...
                'cfg.measurements.isl.twoWay.timeTransfer.useInEKF', ...
                islTimeTransferEkf_, ...
                ternst_(islTimeTransferLive_ && islTimeTransferEkf_,A,IA), ...
                true,'measurementRows,crossSpacecraftCovariance', ...
                'timeTransfer.enable=true and multiAsset.mode=''joint''', ...
                ['Updates both endpoint clock states in the centralized joint ' ...
                 'EKF; false retains the observation as diagnostic metadata']);
            rows{end+1} = MK('Crosslink', ...
                'cfg.measurements.isl.twoWay.timeTransfer.mode', ...
                islTimeTransferMode_,ternst_(islTimeTransferLive_,A,IA),true, ...
                'measurementValue,H', 'timeTransfer.enable=true', ...
                ['firstOrderReciprocal is implemented; fourTimestampPhysical ' ...
                 'is reserved and rejected until primitive timestamp processing exists']);

            % One-way ISL carrier rows and their float ambiguity states. Every entry here is
            % inert unless measurements.isl.enable AND a swarm (nSpaceAssets>1) put real ISL
            % links in the filter.
            islCarEn_  = logical_G_(G('measurements.isl.carrier.enable'));
            islCarEkf_ = logical_G_(G('measurements.isl.carrier.useInEKF'));
            islAmbEn_  = logical_G_(G('measurements.isl.carrier.ambiguity.enable'));
            islSlipEn_ = logical_G_(G('measurements.isl.carrier.slipDetection.enable'));
            islLive_   = islEn_ && nSA_ > 1;

            stIslCar = ternst_(islLive_ && islCarEn_, A, IA);
            rows{end+1} = MK('Crosslink','cfg.measurements.isl.carrier.enable', islCarEn_, stIslCar, true, ...
                'measurementRows', 'isl.enable=true and nSpaceAssets>1', ...
                'One-way ISL carrier-phase rows; needs ambiguity states to be unbiased');
            rows{end+1} = MK('Crosslink','cfg.measurements.isl.carrier.useInEKF', islCarEkf_, ...
                ternst_(islLive_ && islCarEn_ && islCarEkf_, A, IA), true, ...
                'measurementRows,stateDimension', 'isl.carrier.enable=true', ...
                'false = carrier formed but not fed to the update (diagnostic residuals only)');
            rows{end+1} = MK('Crosslink','cfg.measurements.isl.carrier.sigma_m', ...
                G('measurements.isl.carrier.sigma_m'), stIslCar, true, ...
                'R,measurementValue', 'isl.carrier.enable=true', ...
                'ISL carrier 1-sigma. 0.20 m is the defensible default; a mm-class R here diverges the filter unless the ISL geometry genuinely supports it');
            islFreq_ = G('measurements.isl.carrier.frequency_Hz');
            rows{end+1} = MK('Crosslink','cfg.measurements.isl.carrier.frequency_Hz', islFreq_, stIslCar, true, ...
                'measurementValue', 'isl.carrier.enable=true', ...
                'NaN = inherit the L1 ground carrier (190 mm). Set 26e9 for a Ka crosslink (11.5 mm) -- the filter itself works in metres, so this changes only the cycle/metre mapping used by integer AR');

            stIslAmb = ternst_(islLive_ && islCarEn_ && islAmbEn_, A, IA);
            rows{end+1} = MK('Crosslink','cfg.measurements.isl.carrier.ambiguity.enable', islAmbEn_, stIslAmb, true, ...
                'stateDimension', 'isl.carrier.enable=true', ...
                'Float ambiguity state per ISL link+signal, appended after srpScale');
            rows{end+1} = MK('Crosslink','cfg.measurements.isl.carrier.ambiguity.nSignals', ...
                G('measurements.isl.carrier.ambiguity.nSignals'), stIslAmb, false, ...
                'stateDimension', 'isl.carrier.ambiguity.enable=true', ...
                'ISL carrier signals per link; >1 allocates states the builder does not yet populate');
            rows{end+1} = MK('Crosslink','cfg.measurements.isl.carrier.ambiguity.initialSigma_m', ...
                G('measurements.isl.carrier.ambiguity.initialSigma_m'), stIslAmb, true, ...
                'P0', 'isl.carrier.ambiguity.enable=true', ...
                'P0 and slip-reset inflation for each ISL ambiguity');
            rows{end+1} = MK('Crosslink','cfg.measurements.isl.carrier.ambiguity.processNoiseSigma_m_per_sqrt_s', ...
                G('measurements.isl.carrier.ambiguity.processNoiseSigma_m_per_sqrt_s'), stIslAmb, true, ...
                'Q', 'isl.carrier.ambiguity.enable=true', ...
                '0 = constant within an arc (the physically correct choice for a true ambiguity)');

            stIslSlip = ternst_(islLive_ && islCarEn_ && islSlipEn_, A, IA);
            rows{end+1} = MK('Crosslink','cfg.measurements.isl.carrier.slipDetection.enable', islSlipEn_, stIslSlip, true, ...
