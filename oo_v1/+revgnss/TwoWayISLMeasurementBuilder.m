        function calibrationProduct = calibrationProductForLinkDefinitionIndex(cfg, linkDefinitionIndex)
            % calibrationProductForLinkDefinitionIndex  Pure exposure (plan Section 2.3.1): the
            % SAME per-link calibration resolution generateObservations/configForLink_ already
            % perform internally (calibration.productIdentifier is overridden per link), exposed
            % so a distributed-link-update caller can resolve the identical calibration product
            % for a link record without re-deriving configForLink_/hardwareModels_, both private
            % to this class. linkDefinitionIndex==0 (or the legacy no-links path) resolves the
