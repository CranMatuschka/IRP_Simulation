            row = revgnss.ObservableRowDescriptor.withFlags(row,false, ...
                any(ismember(columns,attitudeColumns)));
            info.rows = row;
            if useInEkf
                info.ekfRowTypes = {'islTwoWayRange'};
                info.nEkfRows = 1;
            end
        end

        function value = drawNormal_(cfg,initiatorIdx,transponderIdx,epochIdx)
            seed = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'simulation','seed'},42);
            stream = RandStream('mt19937ar','Seed',mod( ...
                seed + 700001 + 1009*initiatorIdx + 9176*transponderIdx + ...
                104729*epochIdx,2^31-1));
            value = randn(stream,1,1);
        end

        function tf = isEnabled_(cfg)
            tf = revgnss.TwoWayISLMeasurementBuilder.getBool_( ...
                cfg,{'measurements','isl','twoWay','enable'},false) && ...
                revgnss.TwoWayISLMeasurementBuilder.getBool_( ...
                cfg,{'measurements','isl','twoWay','range','enable'},false);
        end

        function tf = getBool_(cfg,path,defaultValue)
            value = revgnss.TwoWayISLMeasurementBuilder.walk_(cfg,path,defaultValue);
            tf = islogical(value) && isscalar(value) && value;
        end

        function value = getNum_(cfg,path,defaultValue)
            value = revgnss.TwoWayISLMeasurementBuilder.walk_(cfg,path,defaultValue);
            if ~isnumeric(value) || ~isscalar(value); value = defaultValue; end
        end

        function value = getStr_(cfg,path,defaultValue)
            value = revgnss.TwoWayISLMeasurementBuilder.walk_(cfg,path,defaultValue);
            if ~(ischar(value) || (isstring(value) && isscalar(value)))
                value = defaultValue;
            end
            value = char(value);
        end

        function value = walk_(cfg,path,defaultValue)
            value = cfg;
            for pathIdx = 1:numel(path)
                if isstruct(value) && isfield(value,path{pathIdx})
                    value = value.(path{pathIdx});
                else
                    value = defaultValue;
                    return
                end
            end
        end
    end
