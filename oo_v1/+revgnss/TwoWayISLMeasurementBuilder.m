        function delay_s = modeledPropagationDelay_(cfg,x,stateMap,info)
            delay_s = 0;
            if ~revgnss.TwoWayISLMeasurementBuilder.getBool_(cfg, ...
                    {'measurements','isl','twoWay','range','plasma','enable'},false)
                return
            end
            initiator = revgnss.AssetStateBlock.forAsset( ...
                stateMap,info.receiverAssetIndex);
            transponder = revgnss.AssetStateBlock.forAsset( ...
                stateMap,info.transmitterAssetIndex);
            if isempty(initiator.r) || isempty(transponder.r)
                return
            end
            distance_m = norm(x(initiator.r)-x(transponder.r));
            [~,modelResult] = ...
                revgnss.TwoWayISLMeasurementBuilder.rfModels_(cfg,distance_m);
            delay_s = (modelResult.forward.plasmaGroupDelay_m + ...
                modelResult.return.plasmaGroupDelay_m)/ ...
                revgnss.TwoWayISLMeasurementBuilder.C_mps;
        end

        function [scheduled,status] = scheduleStatus_(cfg,t_s)
            period = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','schedule','updatePeriod_s'},1);
            phase = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','schedule','updatePhase_s'},0);
            start_s = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','schedule','start_s'},0);
            stop_s = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','schedule','stop_s'},1e12);
            scheduled = false;
            status = 'outsideActiveInterval';
            tolerance = 10*eps(max(1,abs(t_s)));
            if t_s < start_s-tolerance || t_s > stop_s+tolerance
                return
            end
            cycle = (t_s-phase)/period;
            if cycle < -tolerance || abs(cycle-round(cycle)) > tolerance
                status = 'notScheduled';
                return
            end
            outages = revgnss.TwoWayISLMeasurementBuilder.walk_(cfg, ...
                {'measurements','isl','twoWay','schedule','outages_s'},zeros(0,2));
            for outageIdx = 1:size(outages,1)
                if t_s >= outages(outageIdx,1)-tolerance && ...
                        t_s <= outages(outageIdx,2)+tolerance
                    status = 'scheduledOutage';
                    return
                end
            end
            scheduled = true;
            status = 'scheduled';
        end

