            info.thermalSigma_m = thermalSigma;
            info.calibrationSigma_m = sqrt(calibrationVariance);
            if biasStateEnabled
                info.calibrationUncertaintyTreatment = ...
                    'estimatedPersistentResidualBias';
            elseif calibrationVariance > 0
                info.calibrationUncertaintyTreatment = ...
                    'diagnosticMeasurementCovariance';
            else
                info.calibrationUncertaintyTreatment = 'none';
            end
            info.plasmaResidualSigma_m = plasmaResidualSigma;
            info.physicalPropagationGroupDelay_s = physicalPropagationDelay_s;
            info.modeledPropagationGroupDelay_s = modeledPropagationDelay_s;
