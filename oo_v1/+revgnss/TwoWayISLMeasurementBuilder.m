        function [zAdd,hAdd,HAdd,RAdd,info] = ...
                linearizeRecordedObservation( ...
                cfg,observation,x,stateMap,nx,t_s,info)
            if nargin < 7 || isempty(info)
                info = revgnss.TwoWayISLMeasurementBuilder.defaultInfo(cfg,{});
                info.receiverAssetIndex = ...
                    revgnss.TwoWayISLMeasurementBuilder.assetIndexFromIdentifier_( ...
                    observation.initiatorAssetIdentifier);
                info.transmitterAssetIndex = ...
                    revgnss.TwoWayISLMeasurementBuilder.assetIndexFromIdentifier_( ...
                    observation.transponderAssetIdentifier);
                info.linkIdentifier = ...
                    revgnss.TwoWayISLMeasurementBuilder. ...
                    linkIdentifierFromObservation_(observation);
            end
            if nargin < 6 || ~(isscalar(t_s) && isfinite(t_s))
                error('TwoWayISLMeasurementBuilder:predictionEpoch', ...
                    'Recorded-observation processing requires a finite coordinate epoch.');
            end
            if ~isa(observation,'revgnss.InterSatelliteObservationRecord')
                error('TwoWayISLMeasurementBuilder:observationType', ...
                    'Processing requires an immutable inter-satellite observation record.');
            end
            if ~isfield(info,'linkIdentifier') || isempty(info.linkIdentifier)
                info.linkIdentifier = ...
                    revgnss.TwoWayISLMeasurementBuilder. ...
                    linkIdentifierFromObservation_(observation);
            end
            if ~isempty(revgnss.TwoWayISLMeasurementBuilder. ...
                    linkDefinitions(cfg))
                cfg = revgnss.TwoWayISLMeasurementBuilder. ...
                    configForInfo_(cfg,info);
            end
            if nargin < 5 || isempty(nx); nx = numel(x); end
            if numel(x) ~= nx
                error('TwoWayISLMeasurementBuilder:stateDimension', ...
                    'The supplied state dimension does not match the estimator state.');
            end
            info.observationRecord = observation;
            info.protocol = observation.protocolIdentifier;
            info.referenceEpochRule = observation.referenceEpochRule;
            info.rangeSigma_m = sqrt(observation.covarianceBlock( ...
                observation.covarianceRowIndex,observation.covarianceRowIndex));
            info.carrierToNoiseDensity_dBHz = ...
                observation.carrierToNoiseDensity_dBHz;
            info.effectiveRangingBandwidth_Hz = ...
                observation.effectiveRangingBandwidth_Hz;
            info.roundTripLinkMargin_dB = observation.roundTripLinkMargin_dB;
            info.trackingAvailable = observation.available;

            zAdd = []; hAdd = []; HAdd = zeros(0,nx); RAdd = zeros(0);
            if info.rangeUseInEKF && observation.available
                initiatorBlock = revgnss.AssetStateBlock.forAsset( ...
                    stateMap,info.receiverAssetIndex);
                transponderBlock = revgnss.AssetStateBlock.forAsset( ...
                    stateMap,info.transmitterAssetIndex);
                if isempty(initiatorBlock.r) || isempty(transponderBlock.r)
                    error('TwoWayISLMeasurementBuilder:endpointState', ...
                        'Both coherent-ranging endpoints must be estimated states.');
                end
                [~,calibrationProduct] = ...
                    revgnss.TwoWayISLMeasurementBuilder.hardwareModels_(cfg);
                if ~any(strcmp(observation.calibrationProductIdentifiers, ...
                        calibrationProduct.calibrationProductIdentifier))
                    error('TwoWayISLMeasurementBuilder:calibrationIdentity', ...
                        'The configured calibration product does not match the observation.');
                end
                predictedRange = ...
                    revgnss.TwoWayISLMeasurementBuilder.predictFromState_( ...
                    cfg,observation,calibrationProduct,x,stateMap,info,t_s);
                Hrow = revgnss.TwoWayISLMeasurementBuilder.finiteDifferenceRow_( ...
                    cfg,observation,calibrationProduct,x,stateMap,info,t_s,nx);
                biasStateEnabled = ...
                    revgnss.TwoWayISLMeasurementBuilder.getBool_(cfg, ...
                    {'measurements','isl','twoWay','calibration', ...
                    'residualBiasState','enable'},false);
                if biasStateEnabled
                    biasIndex = revgnss.TwoWayISLMeasurementBuilder. ...
                        calibrationBiasIndex_(stateMap,info.linkIdentifier);
                    Hrow(biasIndex) = 1;
                end
                zAdd = observation.processedValue;
                hAdd = predictedRange;
                HAdd = Hrow;
                RAdd = observation.covarianceBlock( ...
                    observation.covarianceRowIndex, ...
                    observation.covarianceRowIndex);
                info = revgnss.TwoWayISLMeasurementBuilder.addMeta_( ...
                    info,Hrow,true,stateMap);
            else
                info = revgnss.TwoWayISLMeasurementBuilder.addMeta_( ...
                    info,[],false,stateMap);
            end
            info.zEkf = zAdd;
            info.hEkf = hAdd;
            if ~isempty(zAdd); info.prefitRms = abs(zAdd-hAdd); end
        end

        function h = predictEkfRows(cfg,~,assets,x,stateMap,info,t_s)
            h = [];
            if isstruct(info) && isfield(info,'linkInfos')
                for linkIndex = 1:numel(info.linkInfos)
                    linkInfo = info.linkInfos{linkIndex};
                    if ~isfield(linkInfo,'observationRecord') || ...
                            isempty(linkInfo.observationRecord) || ...
                            ~linkInfo.rangeUseInEKF || linkInfo.nEkfRows < 1
                        continue
                    end
                    linkCfg = revgnss.TwoWayISLMeasurementBuilder. ...
                        configForInfo_(cfg,linkInfo);
                    [~,calibration] = ...
                        revgnss.TwoWayISLMeasurementBuilder. ...
                        hardwareModels_(linkCfg);
                    h(end+1,1) = ... %#ok<AGROW>
                        revgnss.TwoWayISLMeasurementBuilder.predictFromState_( ...
                        linkCfg,linkInfo.observationRecord,calibration,x, ...
                        stateMap,linkInfo,t_s);
                end
                if isempty(assets); h = []; end
                return
            end
            if isempty(info) || ~isfield(info,'observationRecord') || ...
                    isempty(info.observationRecord) || ~info.rangeUseInEKF
                return
            end
            if ~(isscalar(t_s) && isfinite(t_s))
                error('TwoWayISLMeasurementBuilder:predictionEpoch', ...
                    'Postfit prediction requires the estimator coordinate epoch.');
            end
            [~,calibration] = revgnss.TwoWayISLMeasurementBuilder.hardwareModels_(cfg);
            h = revgnss.TwoWayISLMeasurementBuilder.predictFromState_( ...
                cfg,info.observationRecord,calibration,x,stateMap,info,t_s);
            if isempty(assets); h = []; end
        end

