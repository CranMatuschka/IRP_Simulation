    methods (Static, Access = private)
        function validateLinkDefinitions_(cfg,links,nAssets,period_s,dt_s)
            if isempty(links); return; end
            required = {'linkIdentifier','initiatorAssetIndex', ...
                'transponderAssetIndex','physicalChainIdentifier', ...
                'calibrationProductIdentifier','signalIdentifier', ...
                'channelIdentifier','schedule'};
            identifiers = cell(1,numel(links));
            chainIdentifiers = cell(1,numel(links));
            calibrationIdentifiers = cell(1,numel(links));
            commandIdentifiers = cell(1,numel(links));
            phases_s = zeros(1,numel(links));
            endpoints = zeros(numel(links),2);
            for linkIndex = 1:numel(links)
                missing = setdiff(required,fieldnames(links(linkIndex)));
                if ~isempty(missing)
                    error('TwoWayISLMeasurementBuilder:linkField', ...
                        'Two-way link %d is missing field %s.', ...
                        linkIndex,missing{1});
                end
                endpoints(linkIndex,:) = [ ...
                    links(linkIndex).initiatorAssetIndex, ...
                    links(linkIndex).transponderAssetIndex];
                if any(~isfinite(endpoints(linkIndex,:))) || ...
                        any(endpoints(linkIndex,:) ~= ...
                        round(endpoints(linkIndex,:))) || ...
                        any(endpoints(linkIndex,:) < 1) || ...
                        any(endpoints(linkIndex,:) > nAssets) || ...
                        endpoints(linkIndex,1) == endpoints(linkIndex,2)
                    error('TwoWayISLMeasurementBuilder:linkEndpoints', ...
                        'Each enabled two-way link requires two distinct spacecraft indices.');
                end
                identifiers{linkIndex} = ...
                    revgnss.TwoWayISLMeasurementBuilder.textField_( ...
                    links(linkIndex),'linkIdentifier',linkIndex);
                chainIdentifiers{linkIndex} = ...
                    revgnss.TwoWayISLMeasurementBuilder.textField_( ...
                    links(linkIndex),'physicalChainIdentifier',linkIndex);
                calibrationIdentifiers{linkIndex} = ...
                    revgnss.TwoWayISLMeasurementBuilder.textField_( ...
                    links(linkIndex),'calibrationProductIdentifier',linkIndex);
                revgnss.TwoWayISLMeasurementBuilder.textField_( ...
                    links(linkIndex),'signalIdentifier',linkIndex);
                revgnss.TwoWayISLMeasurementBuilder.textField_( ...
                    links(linkIndex),'channelIdentifier',linkIndex);
                if ~isstruct(links(linkIndex).schedule) || ...
                        ~isfield(links(linkIndex).schedule,'updatePhase_s') || ...
                        ~isfield(links(linkIndex).schedule,'commandIdentifier')
                    error('TwoWayISLMeasurementBuilder:linkSchedule', ...
                        'Each enabled link requires a phase and command identifier.');
                end
                phases_s(linkIndex) = ...
                    links(linkIndex).schedule.updatePhase_s;
                if ~(isscalar(phases_s(linkIndex)) && ...
                        isfinite(phases_s(linkIndex)) && ...
                        phases_s(linkIndex) >= 0 && ...
                        phases_s(linkIndex) < period_s)
                    error('TwoWayISLMeasurementBuilder:linkSchedule', ...
                        'Each link phase must be in [0, updatePeriod_s).');
                end
                if abs(phases_s(linkIndex)/dt_s - ...
                        round(phases_s(linkIndex)/dt_s)) > 1e-10
                    error('TwoWayISLMeasurementBuilder:linkScheduleGrid', ...
                        'Each link phase must align with simulation.dt_s.');
                end
                commandIdentifiers{linkIndex} = ...
                    revgnss.TwoWayISLMeasurementBuilder.textField_( ...
                    links(linkIndex).schedule,'commandIdentifier',linkIndex);
                linkCalibrationErrors = [ ...
                    links(linkIndex).turnaroundCalibrationError_s, ...
                    links(linkIndex).terminalCalibrationError_s];
                if any(~isfinite(linkCalibrationErrors))
                    error('TwoWayISLMeasurementBuilder:linkCalibrationError', ...
                        'Each link calibration error must be finite.');
                end
            end
            revgnss.TwoWayISLMeasurementBuilder.assertUniqueText_( ...
                identifiers,'linkIdentifier');
            revgnss.TwoWayISLMeasurementBuilder.assertUniqueText_( ...
                chainIdentifiers,'physicalChainIdentifier');
            revgnss.TwoWayISLMeasurementBuilder.assertUniqueText_( ...
                calibrationIdentifiers,'calibrationProductIdentifier');
            revgnss.TwoWayISLMeasurementBuilder.assertUniqueText_( ...
                commandIdentifiers,'schedule.commandIdentifier');

            physicalPairs = sort(endpoints,2);
            if size(unique(physicalPairs,'rows'),1) ~= size(physicalPairs,1)
                error('TwoWayISLMeasurementBuilder:duplicatePhysicalLink', ...
                    'A physical spacecraft pair may be declared only once.');
            end
            tolerance = 10*eps(max(1,period_s));
            for firstIndex = 1:numel(links)-1
                for secondIndex = firstIndex+1:numel(links)
                    shareTerminal = any(ismember( ...
                        endpoints(firstIndex,:),endpoints(secondIndex,:)));
                    sameEpoch = abs(phases_s(firstIndex)- ...
                        phases_s(secondIndex)) <= tolerance;
                    if shareTerminal && sameEpoch
                        error('TwoWayISLMeasurementBuilder:terminalScheduleConflict', ...
                            ['Links %s and %s command the same spacecraft terminal ' ...
                             'at the same epoch phase.'], ...
                            identifiers{firstIndex},identifiers{secondIndex});
                    end
                end
            end
            if ~strcmp(revgnss.TwoWayISLMeasurementBuilder.getStr_(cfg, ...
                    {'measurements','isl','twoWay','schedule','commandSource'},''), ...
                    'scenarioOpenLoop')
                error('TwoWayISLMeasurementBuilder:scheduleCommandSource', ...
                    'Declared fleet links require commandSource=scenarioOpenLoop.');
            end
        end

