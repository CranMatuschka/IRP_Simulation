classdef TwoWayISLMeasurementBuilder
    % TwoWayISLMeasurementBuilder  Coherent four-event PN two-way ranging.

    properties (Constant)
        C_mps = 299792458
        Protocol = 'coherentTranspondedPnTwoWayCode'
    end

    methods (Static)
        function validateConfig(cfg)
            parentEnabled = revgnss.TwoWayISLMeasurementBuilder.getBool_( ...
                cfg,{'measurements','isl','twoWay','enable'},false);
            rangeEnabled = revgnss.TwoWayISLMeasurementBuilder.getBool_( ...
                cfg,{'measurements','isl','twoWay','range','enable'},false);
            useRange = revgnss.TwoWayISLMeasurementBuilder.getBool_( ...
                cfg,{'measurements','isl','twoWay','range','useInEKF'},false);
            dopplerRequested = ...
                revgnss.TwoWayISLMeasurementBuilder.getBool_( ...
                cfg,{'measurements','isl','twoWay','doppler','enable'},false) || ...
                revgnss.TwoWayISLMeasurementBuilder.getBool_( ...
                cfg,{'measurements','isl','twoWay','doppler','useInEKF'},false);
            if (rangeEnabled || useRange || dopplerRequested) && ~parentEnabled
                error('TwoWayISLMeasurementBuilder:twoWayParentDisabled', ...
                    'Two-way code and Doppler require twoWay.enable=true.');
            end
            if useRange && ~rangeEnabled
                error('TwoWayISLMeasurementBuilder:rangeUseGuard', ...
                    'twoWay.range.useInEKF requires twoWay.range.enable=true.');
            end
            if dopplerRequested
                error('TwoWayISLMeasurementBuilder:dopplerUnavailable', ...
                    'Coherent two-way Doppler is not implemented and must remain disabled.');
            end
            if ~rangeEnabled
                return
            end
            if ~revgnss.TwoWayISLMeasurementBuilder.getBool_( ...
                    cfg,{'measurements','isl','enable'},false)
                error('TwoWayISLMeasurementBuilder:parentDisabled', ...
                    'The coherent two-way link requires measurements.isl.enable=true.');
            end
            nAssets = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'scenario','nSpaceAssets'},1);
            links = revgnss.TwoWayISLMeasurementBuilder.linkDefinitions(cfg);
            remoteIdx = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','transmitterAssetIndex'},2);
            initiatorIdx = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','receiverAssetIndex'},1);
            if isempty(links) && (nAssets < 2 || remoteIdx < 1 || remoteIdx > nAssets || ...
                    initiatorIdx < 1 || initiatorIdx > nAssets || ...
                    initiatorIdx == remoteIdx)
                error('TwoWayISLMeasurementBuilder:endpoints', ...
                    'A coherent two-way link requires two distinct configured spacecraft.');
            end
            protocol = revgnss.TwoWayISLMeasurementBuilder.getStr_( ...
                cfg,{'measurements','isl','twoWay','protocol'}, ...
                revgnss.TwoWayISLMeasurementBuilder.Protocol);
            if ~strcmp(protocol,revgnss.TwoWayISLMeasurementBuilder.Protocol)
                error('TwoWayISLMeasurementBuilder:protocol', ...
                    'Only coherentTranspondedPnTwoWayCode is implemented.');
            end
            revgnss.TwoWayISLMeasurementBuilder.terminalGeometry_(cfg,1);
            codeRatio = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','twoWay','codeRateTurnaroundRatio'},1);
            if codeRatio ~= 1
                error('TwoWayISLMeasurementBuilder:codeRateRatio', ...
                    'Coherent tracked PN ranging requires codeRateTurnaroundRatio=1.');
            end
            forwardFrequency = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','twoWay','forwardCarrierFrequency_Hz'},NaN);
            returnFrequency = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','twoWay','returnCarrierFrequency_Hz'},NaN);
            carrierRatio = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','twoWay','carrierFrequencyTurnaroundRatio'},NaN);
            if ~(isfinite(forwardFrequency) && forwardFrequency > 0 && ...
                    isfinite(returnFrequency) && returnFrequency > 0 && ...
                    isfinite(carrierRatio) && carrierRatio > 0)
                error('TwoWayISLMeasurementBuilder:carrierFrequency', ...
                    'Forward/return carrier frequencies and turnaround ratio must be positive.');
            end
            if abs(returnFrequency-forwardFrequency*carrierRatio) > ...
                    1e-12*max(returnFrequency,forwardFrequency)
                error('TwoWayISLMeasurementBuilder:carrierFrequencyRatio', ...
                    ['returnCarrierFrequency_Hz must equal forwardCarrierFrequency_Hz ' ...
                     'times carrierFrequencyTurnaroundRatio.']);
            end
            linkModel = revgnss.TwoWayISLMeasurementBuilder.getStr_( ...
                cfg,{'measurements','isl','twoWay','range','linkBudget','model'},'fixed');
            if ~ismember(linkModel,{'fixed','linkBudget','physicalRF'})
                error('TwoWayISLMeasurementBuilder:linkModel', ...
                    'Two-way code link model must be fixed, linkBudget, or physicalRF.');
            end
            plasmaEnabled = revgnss.TwoWayISLMeasurementBuilder.getBool_( ...
                cfg,{'measurements','isl','twoWay','range','plasma','enable'},false);
            if plasmaEnabled && ~strcmp(linkModel,'physicalRF')
                error('TwoWayISLMeasurementBuilder:plasmaRequiresPhysicalRF', ...
                    'ISL plasma group delay requires range.linkBudget.model=''physicalRF''.');
            end
            if plasmaEnabled
                truthTec = [ ...
                    revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                    {'measurements','isl','twoWay','range','plasma','truthForwardTEC_electrons_per_m2'},0), ...
                    revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                    {'measurements','isl','twoWay','range','plasma','truthReturnTEC_electrons_per_m2'},0)];
                modelTec = [ ...
                    revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                    {'measurements','isl','twoWay','range','plasma','estimatorForwardTEC_electrons_per_m2'},0), ...
                    revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                    {'measurements','isl','twoWay','range','plasma','estimatorReturnTEC_electrons_per_m2'},0)];
                residualSigma = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                    {'measurements','isl','twoWay','range','plasma','residualSigma_m'},0);
                if any(~isfinite([truthTec,modelTec,residualSigma])) || ...
                        any([truthTec,modelTec,residualSigma] < 0)
                    error('TwoWayISLMeasurementBuilder:plasmaParameters', ...
                        'TEC values and plasma residual sigma must be finite and nonnegative.');
                end
                if all(truthTec == modelTec) && residualSigma == 0
                    error('TwoWayISLMeasurementBuilder:plasmaTruthModelSeparation', ...
                        ['An enabled plasma truth model must use an independent estimator ' ...
                         'correction or a nonzero residual uncertainty.']);
                end
            end
            if strcmp(linkModel,'physicalRF')
                validationDistance = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                    cfg,{'measurements','isl','twoWay','range','linkBudget', ...
                    'validationDistance_m'},1e5);
                revgnss.TwoWayISLMeasurementBuilder.rfModels_( ...
                    cfg,validationDistance);
            end
            minimumTrackingCn0 = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','twoWay','range','tracking', ...
                'minimumCarrierToNoiseDensity_dBHz'},25);
            if ~(isscalar(minimumTrackingCn0) && isfinite(minimumTrackingCn0))
                error('TwoWayISLMeasurementBuilder:trackingThreshold', ...
                    'The two-way tracking C/N0 threshold must be finite.');
            end
            updatePeriod = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','schedule','updatePeriod_s'},1);
            updatePhase = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','schedule','updatePhase_s'},0);
            dt_s = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'simulation','dt_s'},1);
            if ~(isfinite(updatePeriod) && updatePeriod > 0 && ...
                    isfinite(updatePhase) && updatePhase >= 0 && ...
                    updatePhase < updatePeriod)
                error('TwoWayISLMeasurementBuilder:schedule', ...
                    'Two-way update period and phase define an invalid schedule.');
            end
            if abs(updatePeriod/dt_s-round(updatePeriod/dt_s)) > 1e-10 || ...
                    abs(updatePhase/dt_s-round(updatePhase/dt_s)) > 1e-10
                error('TwoWayISLMeasurementBuilder:scheduleGrid', ...
                    'Two-way update period and phase must align with simulation.dt_s.');
            end
            revgnss.TwoWayISLMeasurementBuilder.validateLinkDefinitions_( ...
                cfg,links,nAssets,updatePeriod,dt_s);
            outages = revgnss.TwoWayISLMeasurementBuilder.walk_(cfg, ...
                {'measurements','isl','twoWay','schedule','outages_s'},zeros(0,2));
            if ~(isnumeric(outages) && size(outages,2) == 2 && ...
                    all(isfinite(outages(:))) && all(outages(:,2) >= outages(:,1)))
                error('TwoWayISLMeasurementBuilder:scheduleOutages', ...
                    'twoWay.schedule.outages_s must be a finite N-by-2 interval matrix.');
            end
            if useRange
                mode = revgnss.TwoWayISLMeasurementBuilder.getStr_( ...
                    cfg,{'multiAsset','mode'},'fast');
                if ~strcmp(mode,'joint')
                    error('TwoWayISLMeasurementBuilder:jointEstimatorRequired', ...
                        ['A physical two-way range must update both endpoints. Set ' ...
                         'multiAsset.mode=''joint'' or keep range.useInEKF=false.']);
                end
            end
            stencil = revgnss.TwoWayISLMeasurementBuilder.getStr_(cfg, ...
                {'measurements','isl','twoWay','range','linearization', ...
                'stencil'},'fivePoint');
            if ~strcmp(stencil,'fivePoint')
                error('TwoWayISLMeasurementBuilder:linearizationStencil', ...
                    'The coherent two-way row uses the validated fivePoint stencil.');
            end
            stepPaths = { ...
                'positionStep_m','velocityStep_mps','attitudeStep_rad', ...
                'clockBiasStep_m','clockDriftStep_mps'};
            for stepIndex = 1:numel(stepPaths)
                stepValue = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                    {'measurements','isl','twoWay','range','linearization', ...
                    stepPaths{stepIndex}},NaN);
                if ~(isscalar(stepValue) && isfinite(stepValue) && stepValue > 0)
                    error('TwoWayISLMeasurementBuilder:linearizationStep', ...
                        'Every two-way linearization step must be positive and finite.');
                end
            end
            turnaroundError_s = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','twoWay','truth', ...
                'turnaroundCalibrationError_s'},0);
            terminalError_s = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','twoWay','truth', ...
                'terminalCalibrationError_s'},0);
            turnaroundSigma_s = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','twoWay','calibration', ...
                'turnaroundSigma_s'},0);
            terminalSigma_s = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','twoWay','calibration', ...
                'terminalSigma_s'},0);
            biasStateEnabled = revgnss.TwoWayISLMeasurementBuilder.getBool_( ...
                cfg,{'measurements','isl','twoWay','calibration', ...
                'residualBiasState','enable'},false);
            biasProcessSigma = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','twoWay','calibration', ...
                'residualBiasState','processNoiseSigma_m_per_sqrt_s'},0);
            calibrationCorrelationModel = ...
                revgnss.TwoWayISLMeasurementBuilder.getStr_(cfg, ...
                {'measurements','isl','twoWay','calibration', ...
                'errorCorrelationModel'},'independentPhysicalChains');
            if ~strcmp(calibrationCorrelationModel,'independentPhysicalChains')
                error('TwoWayISLMeasurementBuilder:sharedCalibrationUnavailable', ...
                    ['Only independent physical-chain calibration states are active. ' ...
                     'Shared terminal calibration requires shared nuisance states.']);
            end
            calibrationValues = [turnaroundError_s,terminalError_s, ...
                turnaroundSigma_s,terminalSigma_s,biasProcessSigma];
            if any(~isfinite(calibrationValues)) || ...
                    any(calibrationValues(3:5) < 0)
                error('TwoWayISLMeasurementBuilder:calibrationParameters', ...
                    'Two-way calibration values must be finite and sigmas nonnegative.');
            end
            validFrom = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','calibration', ...
                'validFromLocalTag_s'},0);
            validUntil = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','calibration', ...
                'validUntilLocalTag_s'},1e12);
            if ~(isfinite(validFrom) && isfinite(validUntil) && ...
                    validUntil >= validFrom)
                error('TwoWayISLMeasurementBuilder:calibrationValidity', ...
                    'The two-way calibration validity interval is invalid.');
            end
            if biasStateEnabled && (~useRange || ...
                    hypot(turnaroundSigma_s,terminalSigma_s) == 0)
                error('TwoWayISLMeasurementBuilder:calibrationBiasState', ...
                    ['The calibration residual-bias state requires an active EKF range ' ...
                     'and nonzero calibration uncertainty.']);
            end
            persistentCalibration = any(calibrationValues(1:4) ~= 0);
            if useRange && persistentCalibration && ~biasStateEnabled
                error('TwoWayISLMeasurementBuilder:persistentCalibrationRequiresState', ...
                    ['A recurring calibration error or uncertainty must use the ' ...
                     'persistent residual-bias state; it cannot be repeated as white R.']);
            end
        end

        function links = linkDefinitions(cfg)
            links = revgnss.TwoWayISLMeasurementBuilder.walk_(cfg, ...
                {'measurements','isl','twoWay','links'},struct([]));
            if isempty(links)
                links = struct([]);
                return
            end
            if ~isstruct(links) || ~isfield(links,'enable')
                error('TwoWayISLMeasurementBuilder:linkDefinitions', ...
                    'twoWay.links must be a struct array with an enable field.');
            end
            enabled = false(1,numel(links));
            for linkIndex = 1:numel(links)
                value = links(linkIndex).enable;
                if ~(islogical(value) && isscalar(value))
                    error('TwoWayISLMeasurementBuilder:linkEnable', ...
                        'Each two-way link enable field must be a logical scalar.');
                end
                enabled(linkIndex) = value;
            end
            links = links(enabled);
        end

        function identifiers = calibrationLinkIdentifiers(cfg)
            links = revgnss.TwoWayISLMeasurementBuilder.linkDefinitions(cfg);
            if isempty(links)
                identifiers = {revgnss.TwoWayISLMeasurementBuilder.getStr_( ...
                    cfg,{'measurements','isl','twoWay','linkIdentifier'}, ...
                    'isl-two-way-code-link-A1-A2')};
                return
            end
            identifiers = arrayfun(@(link) char(link.linkIdentifier),links, ...
                'UniformOutput',false);
        end

        function [zAdd,hAdd,HAdd,RAdd,info] = build( ...
                cfg,primaryAsset,assets,x,stateMap,nx,t_s)
            if nargin < 7; t_s = 0; end
            [observation,truthDiagnostic,info] = ...
                revgnss.TwoWayISLMeasurementBuilder.generateObservation( ...
                cfg,primaryAsset,assets,t_s);
            if isempty(observation)
                zAdd = []; hAdd = []; HAdd = zeros(0,nx); RAdd = zeros(0);
                return
            end
            [zAdd,hAdd,HAdd,RAdd,info] = ...
                revgnss.TwoWayISLMeasurementBuilder.linearizeRecordedObservation( ...
                cfg,observation,x,stateMap,nx,t_s,info);
            info.truthDiagnostic = truthDiagnostic;
        end

        function [observations,truthDiagnostics,info] = ...
                generateObservations(cfg,primaryAsset,assets,t_s)
            if nargin < 4; t_s = 0; end
            observations = {};
            truthDiagnostics = {};
            linkInfos = {};
            links = revgnss.TwoWayISLMeasurementBuilder.linkDefinitions(cfg);
            if isempty(links)
                [observation,diagnostic,linkInfo] = ...
                    revgnss.TwoWayISLMeasurementBuilder.generateObservation( ...
                    cfg,primaryAsset,assets,t_s);
                linkInfo.linkDefinitionIndex = 0;
                if ~isempty(observation)
                    observations = {observation};
                    truthDiagnostics = {diagnostic};
                    linkInfos = {linkInfo};
                end
            else
                for linkIndex = 1:numel(links)
                    linkCfg = revgnss.TwoWayISLMeasurementBuilder. ...
                        configForLink_(cfg,links(linkIndex));
                    [observation,diagnostic,linkInfo] = ...
                        revgnss.TwoWayISLMeasurementBuilder.generateObservation( ...
                        linkCfg,primaryAsset,assets,t_s);
                    linkInfo.linkDefinitionIndex = linkIndex;
                    if isempty(observation); continue; end
                    observations{end+1} = observation; %#ok<AGROW>
                    truthDiagnostics{end+1} = diagnostic; %#ok<AGROW>
                    linkInfos{end+1} = linkInfo; %#ok<AGROW>
                end
            end
            info = revgnss.TwoWayISLMeasurementBuilder.aggregateInfo_( ...
                cfg,assets,linkInfos,observations);
        end

        function [zAdd,hAdd,HAdd,RAdd,info] = ...
                linearizeRecordedObservations( ...
                cfg,observations,x,stateMap,nx,t_s,info)
            if nargin < 7 || isempty(info)
                reconstructedInfos = cell(1,numel(observations));
                for observationIndex = 1:numel(observations)
                    reconstructedInfos{observationIndex} = ...
                        revgnss.TwoWayISLMeasurementBuilder. ...
                        infoForObservation_(cfg,observations{observationIndex});
                end
                info = revgnss.TwoWayISLMeasurementBuilder.aggregateInfo_( ...
                    cfg,{},reconstructedInfos,observations);
            end
            if ~iscell(observations)
                error('TwoWayISLMeasurementBuilder:observationCollection', ...
                    'Plural recorded-observation processing requires a cell array.');
            end
            if ~isfield(info,'linkInfos') || ...
                    numel(info.linkInfos) ~= numel(observations)
                error('TwoWayISLMeasurementBuilder:observationInfoCount', ...
                    'Every recorded observation requires its generation metadata.');
            end

            zAdd = [];
            hAdd = [];
            HAdd = zeros(0,nx);
            RAdd = zeros(0);
            processedInfos = cell(1,numel(observations));
            for observationIndex = 1:numel(observations)
                linkInfo = info.linkInfos{observationIndex};
                linkInfo.truthDiagnostic = [];
                linkCfg = revgnss.TwoWayISLMeasurementBuilder. ...
                    configForInfo_(cfg,linkInfo);
                [zLink,hLink,HLink,RLink,linkInfo] = ...
                    revgnss.TwoWayISLMeasurementBuilder. ...
                    linearizeRecordedObservation( ...
                    linkCfg,observations{observationIndex},x,stateMap,nx, ...
                    t_s,linkInfo);
                processedInfos{observationIndex} = linkInfo;
                if isempty(zLink); continue; end
                zAdd = [zAdd;zLink]; %#ok<AGROW>
                hAdd = [hAdd;hLink]; %#ok<AGROW>
                HAdd = [HAdd;HLink]; %#ok<AGROW>
                RAdd = blkdiag(RAdd,RLink);
            end
            info = revgnss.TwoWayISLMeasurementBuilder.aggregateInfo_( ...
                cfg,{},processedInfos,observations);
            info.zEkf = zAdd;
            info.hEkf = hAdd;
            if ~isempty(zAdd)
                info.prefitRms = sqrt(mean((zAdd-hAdd).^2));
            end
        end

        function [observation,truthDiagnostic,info] = generateObservation( ...
                cfg,primaryAsset,assets,t_s)
            if nargin < 4; t_s = 0; end
            links = revgnss.TwoWayISLMeasurementBuilder.linkDefinitions(cfg);
            if ~isempty(links)
                cfg = revgnss.TwoWayISLMeasurementBuilder. ...
                    configForLink_(cfg,links(1));
            end
            observation = [];
            truthDiagnostic = [];
            info = revgnss.TwoWayISLMeasurementBuilder.defaultInfo(cfg,assets);
            [info.scheduled,info.scheduleStatus] = ...
                revgnss.TwoWayISLMeasurementBuilder.scheduleStatus_(cfg,t_s);
            info.nRangeRows = double(info.rangeEnabled && info.scheduled);
            if ~info.enabled || ~info.rangeEnabled || ~info.scheduled; return; end

            initiator = assets{info.receiverAssetIndex};
            transponder = assets{info.transmitterAssetIndex};
            if info.receiverAssetIndex == 1; initiator = primaryAsset; end

            truthInitiator = revgnss.TwoWayISLMeasurementBuilder.truthEndpoint_( ...
                cfg,initiator,info.receiverAssetIndex,t_s);
            truthTransponder = revgnss.TwoWayISLMeasurementBuilder.truthEndpoint_( ...
                cfg,transponder,info.transmitterAssetIndex,t_s);
            [physicalHardware,calibrationProduct] = ...
                revgnss.TwoWayISLMeasurementBuilder.hardwareModels_(cfg);
            info.physicalChainIdentifier = ...
                physicalHardware.physicalChainIdentifier;
            info.calibrationProductIdentifier = ...
                calibrationProduct.calibrationProductIdentifier;

            events = revgnss.CoherentTwoWayCodeRangingModel. ...
                solvePhysicalEventGeometry( ...
                truthInitiator,truthTransponder,physicalHardware,t_s,struct());
            legDistances_m = [events.forwardRange_m,events.returnRange_m];
            representativeDistance_m = mean(legDistances_m);
            [rfTruth,rfEstimator] = ...
                revgnss.TwoWayISLMeasurementBuilder.rfModels_(cfg,legDistances_m);
            if isempty(rfTruth)
                thermalSigma = revgnss.TwoWayISLMeasurementBuilder.rangeSigma_( ...
                    cfg,representativeDistance_m);
                physicalPropagationDelay_s = 0;
                modeledPropagationDelay_s = 0;
                measuredCn0_dBHz = info.carrierToNoiseDensity_dBHz;
                effectiveBandwidth_Hz = NaN;
            else
                thermalSigma = rfTruth.codeRangeSigma_m;
                physicalPropagationDelay_s = ...
                    (rfTruth.forward.plasmaGroupDelay_m + ...
                    rfTruth.return.plasmaGroupDelay_m)/ ...
                    revgnss.TwoWayISLMeasurementBuilder.C_mps;
                modeledPropagationDelay_s = ...
                    (rfEstimator.forward.plasmaGroupDelay_m + ...
                    rfEstimator.return.plasmaGroupDelay_m)/ ...
                    revgnss.TwoWayISLMeasurementBuilder.C_mps;
                measuredCn0_dBHz = rfTruth.roundTripLimitingCN0_dBHz;
                effectiveBandwidth_Hz = min( ...
                    rfTruth.forward.rangingBandwidth_Hz, ...
                    rfTruth.return.rangingBandwidth_Hz);
            end
            minimumTrackingCn0 = revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'measurements','isl','twoWay','range','tracking', ...
                'minimumCarrierToNoiseDensity_dBHz'},25);
            enforceTrackingThreshold = ...
                revgnss.TwoWayISLMeasurementBuilder.getBool_(cfg, ...
                {'measurements','isl','twoWay','range','tracking', ...
                'enforceThreshold'},false);
            if isnan(measuredCn0_dBHz)
                linkMargin_dB = NaN;
                trackingAvailable = true;
            else
                linkMargin_dB = measuredCn0_dBHz-minimumTrackingCn0;
                trackingAvailable = ~enforceTrackingThreshold || linkMargin_dB >= 0;
            end
            calibrationVariance = ...
                revgnss.TwoWayISLMeasurementBuilder.calibrationVariance_m2_( ...
                calibrationProduct);
            biasStateEnabled = revgnss.TwoWayISLMeasurementBuilder.getBool_( ...
                cfg,{'measurements','isl','twoWay','calibration', ...
                'residualBiasState','enable'},false);
            plasmaResidualSigma = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','range','plasma','residualSigma_m'},0);
            observationVariance = thermalSigma^2 + plasmaResidualSigma^2;
            if ~biasStateEnabled
                observationVariance = observationVariance + calibrationVariance;
            end
            epochIdx = round(t_s/max( ...
                revgnss.TwoWayISLMeasurementBuilder.getNum_( ...
                cfg,{'simulation','dt_s'},1),eps));
            trackingError_s = 2*thermalSigma/ ...
                revgnss.TwoWayISLMeasurementBuilder.C_mps * ...
                revgnss.TwoWayISLMeasurementBuilder.drawNormal_( ...
                cfg,info.receiverAssetIndex,info.transmitterAssetIndex,epochIdx);
            observationId = sprintf('%s:code:e%09d', ...
                info.linkIdentifier,epochIdx);
            metadata = struct( ...
                'observationIdentifier',observationId, ...
                'sessionIdentifier',sprintf('%s:session:e%09d', ...
                    info.linkIdentifier,epochIdx), ...
                'signalIdentifier',info.signalIdentifier, ...
                'channelIdentifier', ...
                    revgnss.TwoWayISLMeasurementBuilder.getStr_(cfg, ...
                    {'measurements','isl','twoWay','channelIdentifier'},'PN-1'), ...
                'forwardCarrierFrequency_Hz', ...
                    revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                    {'measurements','isl','twoWay', ...
                    'forwardCarrierFrequency_Hz'},NaN), ...
                'returnCarrierFrequency_Hz', ...
                    revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                    {'measurements','isl','twoWay', ...
                    'returnCarrierFrequency_Hz'},NaN), ...
                'covarianceGroupIdentifier',observationId, ...
                'covarianceRowIndex',1, ...
                'covarianceBlock_m2',observationVariance, ...
                'carrierToNoiseDensity_dBHz',measuredCn0_dBHz, ...
                'effectiveRangingBandwidth_Hz',effectiveBandwidth_Hz, ...
                'roundTripLinkMargin_dB',linkMargin_dB, ...
                'additionalCalibrationProductIdentifiers',{ ...
                    revgnss.TwoWayISLMeasurementBuilder. ...
                    phaseCentreCalibrationIdentifiers_(cfg, ...
                    info.receiverAssetIndex,info.transmitterAssetIndex)}, ...
                'localTimeSystemIdentifier', ...
                    revgnss.TwoWayISLMeasurementBuilder.getStr_(cfg, ...
                    {'measurements','isl','twoWay','localTimeSystemIdentifier'}, ...
                    'initiatorOnboardClock'), ...
                'timestampReferencePointIdentifier', ...
                    revgnss.TwoWayISLMeasurementBuilder.getStr_(cfg, ...
                    {'measurements','isl','twoWay', ...
                    'timestampReferencePointIdentifier'}, ...
                    'initiatorReceiveTerminal'), ...
                'commandedScheduleIdentifier', ...
                    revgnss.TwoWayISLMeasurementBuilder.getStr_(cfg, ...
                    {'measurements','isl','twoWay','schedule', ...
                    'commandIdentifier'},'open-loop-scenario-schedule'), ...
                'available',trackingAvailable, ...
                'qualityFlags',struct( ...
                    'trackingLocked',trackingAvailable, ...
                    'calibrationValid',true, ...
                    'pointingCommanded',true, ...
                    'pointingModelApplied',false, ...
                    'lineOfSightClear',true, ...
                    'commandSource', ...
                        revgnss.TwoWayISLMeasurementBuilder.getStr_(cfg, ...
                        {'measurements','isl','twoWay','schedule', ...
                        'commandSource'},'scenarioOpenLoop')), ...
                'truthDiagnosticIdentifier',[observationId '-truth']);
            [observation,truthDiagnostic] = ...
                revgnss.CoherentTwoWayCodeRangingModel.simulateObservation( ...
                truthInitiator,truthTransponder,physicalHardware, ...
                calibrationProduct,t_s,metadata,trackingError_s,struct(), ...
                physicalPropagationDelay_s);

            info.observationRecord = observation;
            info.truthDiagnostic = truthDiagnostic;
            info.protocol = observation.protocolIdentifier;
            info.referenceEpochRule = observation.referenceEpochRule;
