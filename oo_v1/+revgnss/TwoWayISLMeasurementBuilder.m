        function cfg = configForInfo_(cfg,info)
            links = revgnss.TwoWayISLMeasurementBuilder.linkDefinitions(cfg);
            if isempty(links); return; end
            linkIndex = 0;
            if isfield(info,'linkDefinitionIndex') && ...
                    isscalar(info.linkDefinitionIndex)
                linkIndex = info.linkDefinitionIndex;
            end
            if linkIndex < 1 || linkIndex > numel(links)
                linkIndex = find(strcmp( ...
                    {links.linkIdentifier},info.linkIdentifier),1);
            end
            if isempty(linkIndex) || linkIndex < 1 || linkIndex > numel(links)
                error('TwoWayISLMeasurementBuilder:linkIdentity', ...
                    'Recorded observation link %s is not declared.', ...
                    info.linkIdentifier);
            end
            cfg = revgnss.TwoWayISLMeasurementBuilder. ...
                configForLink_(cfg,links(linkIndex));
        end

        function info = aggregateInfo_(cfg,assets,linkInfos,observations)
            if isempty(linkInfos)
                info = revgnss.TwoWayISLMeasurementBuilder.defaultInfo(cfg,assets);
            else
                info = linkInfos{1};
            end
            info.linkInfos = linkInfos;
            info.observationRecords = observations;
            info.eligibleObservationRecords = {};
            info.linkIdentifiers = {};
            info.rows = struct([]);
            info.ekfRowTypes = {};
            info.linkEvents = struct([]);
            info.nRangeRows = 0;
            info.nEkfRows = 0;
            for linkIndex = 1:numel(linkInfos)
                linkInfo = linkInfos{linkIndex};
                info.linkIdentifiers{end+1} = ...
                    linkInfo.linkIdentifier; %#ok<AGROW>
                info.nRangeRows = info.nRangeRows + linkInfo.nRangeRows;
                info.nEkfRows = info.nEkfRows + linkInfo.nEkfRows;
                if ~isempty(linkInfo.rows)
                    info.rows = [info.rows,linkInfo.rows]; %#ok<AGROW>
                end
                if ~isempty(linkInfo.ekfRowTypes)
                    info.ekfRowTypes = [info.ekfRowTypes, ...
                        linkInfo.ekfRowTypes]; %#ok<AGROW>
                end
                if ~isempty(linkInfo.linkEvents)
                    info.linkEvents = [info.linkEvents, ...
                        linkInfo.linkEvents]; %#ok<AGROW>
                end
                if linkInfo.nEkfRows > 0 && ...
                        ~isempty(linkInfo.observationRecord)
                    info.eligibleObservationRecords{end+1} = ...
                        linkInfo.observationRecord; %#ok<AGROW>
                end
            end
            if numel(observations) == 1
                info.observationRecord = observations{1};
            else
                info.observationRecord = [];
            end
            info.scheduled = ~isempty(observations);
            if info.scheduled
                info.scheduleStatus = 'scheduledLinks';
            else
                info.scheduleStatus = 'noScheduledLinks';
            end
        end

        function index = calibrationBiasIndex_(stateMap,linkIdentifier)
            if ~isfield(stateMap,'twoWayCodeCalibrationBiasIdx') || ...
                    isempty(stateMap.twoWayCodeCalibrationBiasIdx)
                error('TwoWayISLMeasurementBuilder:calibrationBiasState', ...
                    'The configured link has no calibration-bias state.');
            end
            indices = stateMap.twoWayCodeCalibrationBiasIdx(:);
            if numel(indices) == 1
                index = indices(1);
                return
            end
            if ~isfield(stateMap,'twoWayCodeCalibrationBiasLinkIdentifiers') || ...
                    numel(stateMap.twoWayCodeCalibrationBiasLinkIdentifiers) ~= ...
                    numel(indices)
                error('TwoWayISLMeasurementBuilder:calibrationBiasMap', ...
                    'Per-link calibration-bias identifiers are missing.');
            end
            match = find(strcmp( ...
                stateMap.twoWayCodeCalibrationBiasLinkIdentifiers, ...
                linkIdentifier),1);
            if isempty(match)
                error('TwoWayISLMeasurementBuilder:calibrationBiasLink', ...
                    'No calibration-bias state is assigned to link %s.', ...
                    linkIdentifier);
            end
            index = indices(match);
        end

