        function identifier = linkIdentifierFromObservation_(observation)
            token = regexp(observation.observationIdentifier, ...
                '^(.*):code:e[0-9]+$','tokens','once');
            if isempty(token)
                error('TwoWayISLMeasurementBuilder:observationLinkIdentity', ...
                    'The observation identifier does not contain its physical link.');
            end
            identifier = token{1};
        end

        function assetIndex = assetIndexFromIdentifier_(identifier)
            token = regexp(char(identifier),'^asset:(\d+)$','tokens','once');
            if isempty(token)
                error('TwoWayISLMeasurementBuilder:assetIdentifier', ...
                    ['The recorded asset identifier cannot be mapped to the ' ...
                     'configured joint state.']);
            end
            assetIndex = str2double(token{1});
            if ~(isfinite(assetIndex) && assetIndex >= 1 && ...
                    assetIndex == round(assetIndex))
                error('TwoWayISLMeasurementBuilder:assetIdentifier', ...
                    'The recorded asset identifier contains an invalid index.');
            end
        end

        function endpoint = truthEndpoint_(cfg,asset,assetIdx,t_s)
            [rInertial,vInertial] = models.frames.FrameTimeUtils.ecefStateToInertial( ...
                asset.r_ecef_m,asset.v_ecef_mps,t_s);
            bodyToInertial = models.frames.FrameTimeUtils.rotMatEcefToInertial(t_s) * ...
                revgnss.AttitudeKinematics.bodyToEcefRotation( ...
                asset.attitude_euler_rad);
            bias_s = asset.clock.getBiasMeters()/ ...
                revgnss.TwoWayISLMeasurementBuilder.C_mps;
            localClockRate = 1 + asset.clock.getDriftMetersPerSecond()/ ...
                revgnss.TwoWayISLMeasurementBuilder.C_mps;
            properTimeRate = ...
                revgnss.TwoWayISLMeasurementBuilder.properTimeRate_( ...
                rInertial,vInertial);
            geometry = revgnss.TwoWayISLMeasurementBuilder. ...
                terminalGeometry_(cfg,assetIdx);
            endpoint = revgnss.TwoWayCodeEndpointModel.constantVelocity( ...
                'physicalTruth',sprintf('asset:%d',assetIdx),rInertial,vInertial,t_s, ...
                bodyToInertialRotation=bodyToInertial, ...
                transmitPhaseCentreOffset_body_m=geometry.transmitOffset_body_m, ...
                receivePhaseCentreOffset_body_m=geometry.receiveOffset_body_m, ...
                transmitTerminalIdentifier=geometry.transmitTerminalIdentifier, ...
                receiveTerminalIdentifier=geometry.receiveTerminalIdentifier, ...
                transmitAntennaIdentifier=geometry.transmitAntennaIdentifier, ...
                receiveAntennaIdentifier=geometry.receiveAntennaIdentifier, ...
                clockLocalTimeAtReference_s=t_s+bias_s, ...
                localClockRate=localClockRate, ...
