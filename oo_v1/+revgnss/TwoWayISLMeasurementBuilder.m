        function row = finiteDifferenceRow_(cfg,observation,calibration,x, ...
                stateMap,info,t_s,nx)
            row = zeros(1,nx);
            initiator = revgnss.AssetStateBlock.forAsset( ...
                stateMap,info.receiverAssetIndex);
            transponder = revgnss.AssetStateBlock.forAsset( ...
                stateMap,info.transmitterAssetIndex);
            columns = [initiator.r;initiator.v;initiator.euler; ...
                initiator.b;initiator.bdot;transponder.r;transponder.v; ...
                transponder.euler;transponder.b;transponder.bdot];
            positionStep = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','range','linearization', ...
                'positionStep_m'},0.5);
            velocityStep = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','range','linearization', ...
                'velocityStep_mps'},0.05);
            attitudeStep = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','range','linearization', ...
                'attitudeStep_rad'},1e-3);
            clockBiasStep = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','range','linearization', ...
                'clockBiasStep_m'},10);
            clockDriftStep = revgnss.TwoWayISLMeasurementBuilder.getNum_(cfg, ...
                {'measurements','isl','twoWay','range','linearization', ...
                'clockDriftStep_mps'},0.01);
            steps = [repmat(positionStep,3,1);repmat(velocityStep,3,1); ...
                repmat(attitudeStep,3,1);clockBiasStep;clockDriftStep; ...
                repmat(positionStep,3,1);repmat(velocityStep,3,1); ...
                repmat(attitudeStep,3,1);clockBiasStep;clockDriftStep];
            for columnIdx = 1:numel(columns)
                stateIndex = columns(columnIdx);
                step = steps(columnIdx);
                xp2 = x; xp1 = x; xm1 = x; xm2 = x;
                xp2(stateIndex) = xp2(stateIndex)+2*step;
                xp1(stateIndex) = xp1(stateIndex)+step;
                xm1(stateIndex) = xm1(stateIndex)-step;
                xm2(stateIndex) = xm2(stateIndex)-2*step;
                hp2 = revgnss.TwoWayISLMeasurementBuilder.predictFromState_( ...
                    cfg,observation,calibration,xp2,stateMap,info,t_s);
                hp1 = revgnss.TwoWayISLMeasurementBuilder.predictFromState_( ...
                    cfg,observation,calibration,xp1,stateMap,info,t_s);
                hm1 = revgnss.TwoWayISLMeasurementBuilder.predictFromState_( ...
                    cfg,observation,calibration,xm1,stateMap,info,t_s);
                hm2 = revgnss.TwoWayISLMeasurementBuilder.predictFromState_( ...
                    cfg,observation,calibration,xm2,stateMap,info,t_s);
                row(stateIndex) = (-hp2+8*hp1-8*hm1+hm2)/(12*step);
            end
        end

