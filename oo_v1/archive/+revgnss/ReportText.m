classdef ReportText
    % ReportText  Standard descriptive text blocks for report sections.
    %
    % All methods return cell arrays of char lines.
    methods (Static)

        function lines = simulatorDescription(nTwr, dur)
            % simulatorDescription  Abstract paragraph describing the run.
            if nargin < 1; nTwr = 5;    end
            if nargin < 2; dur  = 3600; end
            lines = { ...
                sprintf('This report documents a reverse-GNSS simulation using the oo_v1 MATLAB'), ...
                sprintf('simulator.  A ground-based network of %d towers transmits signals', nTwr), ...
                sprintf('received by a GEO space asset over %.0f seconds.', dur), ...
            };
        end

        function lines = scientificLimitations()
            % scientificLimitations  Non-negotiable simulator limitations.
            lines = { ...
                'Scientific limitations (non-negotiable):'; ...
                '  * No integer ambiguity fixing (float ambiguities only)'; ...
                '  * Raw L1 carrier only  —  no L2 carrier EKF, no carrier IF'; ...
                '  * No ANTEX, IONEX, SP3, CLK, or RINEX parsers'; ...
                '  * No VMF3 / GPT3 / ERA5 troposphere models'; ...
                '  * No PPP-grade claim; no centimeter or millimeter accuracy guarantee'; ...
                '  * No Klobuchar ionosphere model'; ...
                '  * No real satellite or tower clock products ingested'; ...
            };
        end

        function lines = supportedFeatures()
            % supportedFeatures  List of implemented (supported) features.
            lines = { ...
                'Supported features (implemented):'; ...
                '  [+] Reverse-GNSS code pseudorange EKF'; ...
                '  [+] L1 single-frequency or L1/L2 ionosphere-free code'; ...
                '  [+] Simplified Doppler (ECEF line-of-sight velocity)'; ...
                '  [+] Raw L1 float carrier EKF (ekfFloat mode)'; ...
                '  [+] ZWD residual state (perTowerZwd mode)'; ...
                '  [+] Tower-clock modes: none / perfectTruth / history / product'; ...
                '  [+] Antenna PCV: none / toy (elevation-only) / table'; ...
                '  [+] Ionosphere mapping: simpleSecant (1/sin) / thinShell'; ...
                '  [+] Sagnac / Shapiro / light-time (sagnacFirstOrder or iterative)'; ...
                '  [+] Observability diagnostics (numerical rank, condition number)'; ...
                '  [+] MATLAB multi-page PDF report'; ...
                '  [+] Optional LaTeX (.tex) source file with compileTex support'; ...
            };
        end

        function lines = notSupportedFeatures()
            % notSupportedFeatures  List of features NOT implemented.
            lines = { ...
                'Not implemented (out of scope for v1):'; ...
                '  [-] PPP-grade, centimeter, or millimeter accuracy'; ...
                '  [-] Integer ambiguity resolution (LAMBDA / MLAMBDA)'; ...
                '  [-] L2 carrier EKF rows'; ...
                '  [-] Carrier ionosphere-free combination (phase IF)'; ...
                '  [-] Phase wind-up'; ...
                '  [-] ANTEX / IONEX / SP3 / CLK / RINEX file parsers'; ...
                '  [-] VMF3 / GPT3 / ERA5 troposphere models'; ...
                '  [-] Klobuchar ionosphere model'; ...
                '  [-] Full relativistic ECI treatment'; ...
                '  [-] Real GNSS data ingest'; ...
            };
        end

    end
end
