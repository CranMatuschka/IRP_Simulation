    % ---- clocks and the degeneracy-breaking observable -----------------------------------
    nFail = nFail + chk(strcmp(g('asset.clockType','?'), 'CESIUM1'), ...
        'the conservative literature-anchored clock template, not the optimistic legacy table');
    nFail = nFail + chk(strcmp(g('clock.mode','?'), 'spacecraftReceiverClockOnly'), ...
