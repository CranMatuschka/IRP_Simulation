% test_golden_baseline  The contract gate for the two reference scenarios.
%
%   config/golden_baseline.json        (single asset, 4 antennas)
%   config/golden_baseline_multi.json  (N = 6 federated formation, 4 antennas each)
%
% WHAT THIS TEST IS FOR. Those two files are the reference configuration every later analysis
% is compared against, and every value in them is defended in docs/golden_baseline_provenance.md.
% A defensible baseline is only defensible while the config it resolves to still matches the
% document. This test asserts the SCIENTIFIC CONTRACT -- the specific choices the provenance
% document argues for -- not merely that the files parse.
%
% It also asserts the property that makes the PAIR interpretable: the single-asset and
% multi-asset baselines must share a byte-identical error model, so that any difference between
% their results is attributable to the formation and to nothing else. Change one, change both.
%
% v2.0 (four receive antennas). The baselines moved from one antenna to four. Three groups of
% assertions exist only because of that:
%   * the two ANTENNA-SCOPE GATES. Amplitude scintillation and coloured code multipath are
%     physically common to all four phase centres and were drawn independently per antenna,
%     which averages them down by sqrt(4) for free while R shrinks to match -- invisible to
%     every consistency metric. Both gates must be on.
%   * the FOUR ANTENNAS ARE NOT AN ATTITUDE SENSOR. finalizeConfig switches
%     estimateAttitudeFromPseudorange on above one antenna and the use*Partials flags switch
%     it back off; the test pins the outcome so the decision cannot drift silently.
%   * the MULTI-ASSET FLEET IS HOMOGENEOUS. cfg.assets(2..6) carries a stale single-column
%     lever arm from MultiAssetConfig.cloneAsset_; the federated runtime rebuilds each leaf
%     from cfg.asset, so all six spacecraft really do get four antennas. That is asserted on
%     the path that actually runs, so the stale clone cannot start being read unnoticed.
%
% TWO MODES.
%   DEFAULT (fast, always runs). Resolves both scenarios and checks the contract. No simulation
%     is run, so this costs a few seconds.
%   FULL (set OO_V1_GOLDEN=1). Additionally executes both scenarios end to end at a shortened
%     120 s duration and asserts that the pipeline completes, that the row composition is the
%     one the provenance document claims, that the two-way time-transfer rows really are in the
%     filter (the one structural claim the whole covariance rests on), and that the formation's
%     relative layer produces a finite shape solution.
%
% To freeze a numeric fingerprint of a FULL-LENGTH run for later comparison:
%   out = run_oo_v1('golden_baseline_multi.json');
%   fp  = revgnss.GoldenRunFingerprint.fromRun(out, [], ...
%             fullfile('config','golden_baseline_multi.json'));
%   revgnss.GoldenRunFingerprint.write(fp, fullfile('tests','golden','golden_baseline_multi.json'));
% If that file exists this test checks the scenario SHA-256 against it, which catches the
% failure mode that makes a golden worse than useless: a scenario edited without re-cutting the
% golden, so the gate passes while measuring something else.

fprintf('== test_golden_baseline ==\n');

thisDir = fileparts(mfilename('fullpath'));
root    = fileparts(thisDir);
addpath(root);
addpath(fullfile(root, 'config'));
addpath(fullfile(root, 'config', 'internal'));

warnState = warning('query', 'ConfigFactory:rxCarrierBiasAbsorbed');
warning('off', 'ConfigFactory:rxCarrierBiasAbsorbed');
warnCleanup = onCleanup(@() warning(warnState.state, 'ConfigFactory:rxCarrierBiasAbsorbed')); %#ok<NASGU>

single_ = 'golden_baseline.json';
multi_  = 'golden_baseline_multi.json';
paths   = struct('single', fullfile(root,'config',single_), ...
                 'multi',  fullfile(root,'config',multi_));
assert(isfile(paths.single), 'Missing scenario: %s', paths.single);
assert(isfile(paths.multi),  'Missing scenario: %s', paths.multi);

% ==========================================================================================
% 1. Resolution: both files resolve, finalisation is idempotent, no leaf is silently overridden
% ==========================================================================================
[cfgS, mdS] = resolveSimulationConfig(paths.single);
[cfgM, mdM] = resolveSimulationConfig(paths.multi);

for c = {{'single', cfgS, mdS}, {'multi', cfgM, mdM}}
    nm = c{1}{1}; cfg = c{1}{2}; md = c{1}{3};
    assert(isequaln(cfg, revgnss.ConfigFactory.finalizeConfig(cfg)), ...
        '%s: configuration finalisation is not idempotent.', nm);
    changed = {};
    for i = 1:numel(md.explicitPaths)
        p = md.explicitPaths{i};
        if ~isequaln(i_get(md.preResolutionConfig, p, '<absent>'), i_get(cfg, p, '<absent>'))
            changed{end+1} = p; %#ok<AGROW>
        end
    end
    assert(isempty(changed), ...
        ['%s: resolution overrode scenario-owned leaves, so the file no longer says what it ' ...
         'does:\n  %s'], nm, strjoin(changed, sprintf('\n  ')));
    fprintf('  ok   %s: resolves, idempotent, %d explicit leaves all survive\n', ...
        nm, numel(md.explicitPaths));
end

