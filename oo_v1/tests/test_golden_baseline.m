        ['two-way time transfer is IN THE FILTER. Without it the GEO radial <-> clock ' ...
         'degeneracy is exact (corr -1.000000) and no radial covariance statement is honest.']);
    nFail = nFail + chk(isequal(g('measurements.twoWayTimeTransfer.conservativeProductCorrelation',false), true), ...
        'the reference-clock product correlation is treated conservatively');

    % ---- measurement noise ---------------------------------------------------------------
    nFail = nFail + chk(abs(g('measurements.doppler.sigma_mps',0) - 0.03*sqrt(2)) < 5e-4, ...
        ['the Doppler sigma carries the documented sqrt(2) inflation for the identical-L1/L2 ' ...
         'noise draw (0.03 * sqrt(2) = %.4f), got %.4f'], 0.03*sqrt(2), g('measurements.doppler.sigma_mps',0));
    nFail = nFail + chk(g('measurements.carrier.sigma_m',0) >= 0.010 - 1e-12, ...
        ['the carrier sigma is >= 10 mm because phase wind-up, phase multipath and the PCV ' ...
         'calibration residual are NOT modelled and must be paid for in R']);
    nFail = nFail + chk(g('measurement.sigmaFloor_m',0) >= 0.01 - 1e-12, ...
