                        isequal(g('estimator.dynamics.perturbations.luniSolar.enable',false), true), ...
        'third-body luni-solar is in BOTH propagators (a real GEO OD filter models it)');
    nFail = nFail + chk(isequal(g('orbit.truth.perturbations.srp.enable',false), true) && ...
                        isequal(g('estimator.dynamics.perturbations.srp.enable',false), true), ...
        'SRP is in BOTH propagators');
    crT = g('orbit.truth.perturbations.srp.Cr',NaN);
    crE = g('estimator.dynamics.perturbations.srp.Cr',NaN);
    relGap = abs(crT - crE) / crT;
    nFail = nFail + chk(relGap > 0 && relGap < 0.15, ...
        ['the ONLY dynamic gap is a declared reflectivity error: |Cr_truth - Cr_ekf|/Cr = %.3f ' ...
         'must be non-zero (an honest gap) and small (a parameter error, not a missing force)'], relGap);
    nFail = nFail + chk(isequal(g('estimator.processNoise.modelMismatch.enable',true), false), ...
        ['modelMismatch stays off: sigma_accel_mps2 already covers the declared gap ~180x, and ' ...
         'charging both would count the same uncertainty twice']);
    nFail = nFail + chk(g('estimator.sigma_accel_mps2',0) > 0, ...
        'a residual-acceleration process noise is declared');

    % ---- no unearned states --------------------------------------------------------------
    nFail = nFail + chk(isequal(g('estimator.srpCoefficient.enable',true), false), ...
        'the SRP scale state is off (measured to converge to 0.748 against a truth of 1.0)');
    nFail = nFail + chk(isequal(g('estimator.empiricalAccel.enable',true), false), ...
        'empirical accelerations are off (measured NEES 25.6 -> 25.4, i.e. nothing)');
    nFail = nFail + chk(isequal(g('estimator.lambda.enable',true), false), ...
        'integer ambiguity resolution is off (unvendored external toolbox; float is honest)');
    nFail = nFail + chk(strcmp(g('estimation.ambiguityMode','?'), 'floatPerTowerReceiverSignal'), ...
        ['float carrier ambiguities per tower x receiver x signal -- the only legal mode above ' ...
         'one antenna, and what absorbs the inter-antenna carrier bias']);
end

