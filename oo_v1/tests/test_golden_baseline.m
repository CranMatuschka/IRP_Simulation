         '(not an oracle) and <= 1 mas (not an uncorrected pole)'], dXp, dYp);
    nFail = nFail + chk(isequal(g('effects.solidEarthTide.truth.enable',true), false), ...
        ['the solid-Earth tide is NOT injected: the implementation is truth-only, so leaving it ' ...
