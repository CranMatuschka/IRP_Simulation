% ==========================================================================================
% 2b. The attitude VARIANT (config/golden_baseline_attitude.json)
% ==========================================================================================
% golden_baseline.json runs four antennas that contribute nothing to attitude. That variant is
% the controlled experiment which measures what they WOULD buy. It is only a controlled
% experiment while it differs from the single-asset baseline in the three declared leaves and
% NOTHING else, so that is what this block asserts.
attFile = fullfile(root, 'config', 'golden_baseline_attitude.json');
if ~isfile(attFile)
    fprintf('  --   golden_baseline_attitude.json absent; attitude-variant contract not checked\n');
else
    [cfgA, mdA] = resolveSimulationConfig(attFile);
    gA   = @(p, d) i_get(cfgA, p, d);
    chkA = @(cond, msg, varargin) i_check(cond, ['attitude: ' msg], varargin{:});

    assert(isequaln(cfgA, revgnss.ConfigFactory.finalizeConfig(cfgA)), ...
        'attitude: configuration finalisation is not idempotent.');
    changedA = {};
    for i = 1:numel(mdA.explicitPaths)
        p = mdA.explicitPaths{i};
        if ~isequaln(i_get(mdA.preResolutionConfig, p, '<absent>'), i_get(cfgA, p, '<absent>'))
            changedA{end+1} = p; %#ok<AGROW>
        end
    end
    nFail = nFail + chkA(isempty(changedA), ...
        'resolution overrode scenario-owned leaves:\n  %s', strjoin(changedA, sprintf('\n  ')));

    nFail = nFail + chkA(strcmp(gA('estimator.attitudeCarrierMode','?'), ...
                                'calibratedDifferentialAmbiguity'), ...
        'the differential carrier-attitude path is ON (that is the whole point of the file)');
    nFail = nFail + chkA(strcmp(gA('estimator.diffAtt.referenceMode','?'), 'selfCalibrated'), ...
        ['referenceMode must be selfCalibrated -- externalInitialAttitude raises ' ...
         'externalReferenceUnavailable, and a truth-derived reference would be truth assistance']);
    nFail = nFail + chkA(isequal(gA('estimator.diffAtt.ambiguityResolution.enable',true), false), ...
        ['integer resolution on the attitude baselines stays off: with the line bias truth-only ' ...
         'the phase-bias status is notCalibratedExternalProduct and the fix is refused anyway']);
    nFail = nFail + chkA(isequal(gA('estimator.attitude.useCodePartials',true), false), ...
        'code attitude partials stay off here too (~2e-5 of the star tracker''s information)');

    % The line bias MUST be calibrated here and uncalibrated in the baseline -- the two changes
    % are one decision (see the file's _whyTheBiasMustChange).
    bA = gA('errors.interAntennaCarrierBias.sigma_cycles', NaN);
    bS = i_get(cfgS, 'errors.interAntennaCarrierBias.sigma_cycles', NaN);
    nFail = nFail + chkA(bA < bS && bA > 0, ...
        ['the inter-antenna line bias must be CALIBRATED here (%.3f cyc) and uncalibrated in ' ...
         'the baseline (%.3f cyc), and still non-zero: differential attitude reads exactly the ' ...
         'phase differences a line bias corrupts'], bA, bS);
    nFail = nFail + chkA(bA * 0.1903 < i_get(cfgS,'measurements.carrier.sigma_m',0), ...
        ['the calibrated residual (%.4f m at L1) must sit BELOW the carrier sigma -- otherwise ' ...
         'the bias is still the dominant term on the attitude baselines and nothing was gained'], ...
        bA * 0.1903);

    % Everything else must match the single-asset baseline exactly.
    attAllowed = {'errors.interAntennaCarrierBias.sigma_cycles'};
    driftA = {};
    for i = 1:numel(sharedPaths)
        p = sharedPaths{i};
        if any(strcmp(p, attAllowed)); continue; end
        if ~isequaln(i_get(cfgS,p,'<absent>'), i_get(cfgA,p,'<absent>'))
            driftA{end+1} = p; %#ok<AGROW>
        end
    end
    nFail = nFail + chkA(isempty(driftA), ...
        ['the attitude variant has drifted from the single-asset baseline on %d leaf/leaves ' ...
         'outside the declared delta, so it is no longer a controlled experiment:\n  %s'], ...
        numel(driftA), strjoin(driftA, sprintf('\n  ')));
    if isempty(driftA)
        fprintf(['  ok   attitude variant: resolves, idempotent, %d explicit leaves survive, and ' ...
                 'differs from the baseline only in the declared delta\n'], numel(mdA.explicitPaths));
    end
end

% ==========================================================================================
% 3. Frozen fingerprints, if any have been cut
% ==========================================================================================
for c = {{single_, paths.single}, {multi_, paths.multi}}
    [~, stem] = fileparts(c{1}{1});
    fpPath = fullfile(thisDir, 'golden', [stem '.json']);
    if ~isfile(fpPath)
        fprintf('  --   %s: no frozen fingerprint yet (see this file''s header for how to cut one)\n', stem);
        continue
    end
    frozen = revgnss.GoldenRunFingerprint.read(fpPath);
    sha    = revgnss.GoldenRunFingerprint.fileSha256(c{1}{2});
    if isfield(frozen,'scenarioSha256') && ~strcmp(sha, frozen.scenarioSha256)
        nFail = nFail + 1;
        fprintf(2, ['  FAIL %s: the scenario changed since the fingerprint was cut\n' ...
                    '        frozen %s\n        actual %s\n' ...
                    '        Re-run and re-cut it, recording why in tests/golden/README_golden.md.\n'], ...
            stem, frozen.scenarioSha256, sha);
    else
        fprintf('  ok   %s: frozen fingerprint matches the scenario sha256\n', stem);
    end
end

% ==========================================================================================
% 4. FULL mode: execute both scenarios (shortened) and check the load-bearing claims
% ==========================================================================================
if isempty(getenv('OO_V1_GOLDEN'))
    fprintf(['  NOTE simulations were NOT run. Set OO_V1_GOLDEN=1 to execute both baselines at\n' ...
             '       120 s and assert row composition and relative-layer output.\n']);
else
    fprintf('  running both baselines end to end at 120 s (OO_V1_GOLDEN is set)...\n');

    cfg = i_shorten(cfgS, 120);
    sim = revgnss.ReverseGNSSSimulation(cfg);
    sim.initialize();
    sim.run();
    rows = median(sim.simData.getNumMeasurementRows());
    % Derived, not hard-coded, so the expectation follows the topology:
    %   code     nT x nAnt x nSig  (both frequencies)          = 40
    %   Doppler  nT x nAnt x nSig  (both frequencies)          = 40
    %   carrier  nT x nAnt         (L1+L2 collapsed to one
    %                               ionosphere-free row/pair)  = 20
    %   two-way  nT                (does NOT scale w/ antenna) =  5
    nT_  = cfgS.scenario.nTowers;
    nA_  = cfgS.scenario.nReceivers;
    nS_  = sum(logical(cfgS.signals.enabledMask(:)));
    want = 2*nT_*nA_*nS_ + nT_*nA_ + nT_;
    nFail = nFail + i_check(rows == want, ...
        ['single: expected %g filter rows per epoch (%d code + %d Doppler + %d carrier + %d ' ...
         'two-way at nTowers=%d, nReceivers=%d, nSignals=%d), got %g. A missing block means an ' ...
         'observable this baseline claims to use is not reaching the filter.'], ...
        want, nT_*nA_*nS_, nT_*nA_*nS_, nT_*nA_, nT_, nT_, nA_, nS_, rows);
    posRms = rms(sim.simData.getPositionErrors());
    nFail = nFail + i_check(isfinite(posRms) && posRms > 0, ...
        'single: position error RMS must be finite and non-zero, got %g', posRms);
    fprintf('  ok   single: %g rows/epoch, position RMS %.3f m over 120 s\n', rows, posRms);

    cfgm = i_shorten(cfgM, 120);
    outM = revgnss.ReportRunner.runSingle(cfgm);
    nFail = nFail + i_check(isstruct(outM) && isfield(outM,'rel') && isstruct(outM.rel), ...
        'multi: the federated run produced no relative layer');
    if isstruct(outM) && isfield(outM,'rel') && isfield(outM.rel,'shapeErrSolved_m')
        s = outM.rel.shapeErrSolved_m;
        nFail = nFail + i_check(isfinite(s) && s > 0, ...
            'multi: solved shape error must be finite and non-zero, got %g', s);
        fprintf('  ok   multi: shape raw %.3f m -> solved %.3f m over 120 s\n', ...
            i_get(outM.rel,'shapeErrRaw_m',NaN), s);
    end
end

assert(nFail == 0, 'test_golden_baseline: %d contract violation(s)', nFail);
fprintf('test_golden_baseline PASSED\n');

% ==========================================================================================
function n = i_check(cond, msg, varargin)
    if cond
        n = 0;
    else
        n = 1;
        fprintf(2, '  FAIL %s\n', sprintf(msg, varargin{:}));
    end
end

function v = i_get(s, dottedPath, dflt)
    v = dflt;
    f = strsplit(dottedPath, '.');
    c = s;
    for i = 1:numel(f)
        if ~isstruct(c) || ~isfield(c, f{i}); return; end
        c = c.(f{i});
    end
    v = c;
end

function cfg = i_shorten(cfg, dur_s)
    cfg.simulation.duration_s    = dur_s;
    cfg.report.writePdf          = false;
    cfg.report.writeMat          = false;
    cfg.report.writeTex          = false;
    cfg.report.compileTex        = 'never';
    cfg.report.monteCarlo.enable = false;
    cfg.plots.enable             = false;
    cfg.plots.saveIndividualFigures = false;
    cfg.plots.savePdf            = false;
    cfg.report.reportFolder      = tempname;
    mkdir(cfg.report.reportFolder);
    cfg.report.stem              = 'golden_baseline_check';
    cfg = revgnss.ConfigFactory.finalizeConfig(cfg);
end
