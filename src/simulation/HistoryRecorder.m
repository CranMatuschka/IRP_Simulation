                atmosphereTruthTroposphereResidualByTower_m(:).', ...
                sim.numReceivers, ...
                1);

            truthIonosphereResidualByReceiverTower_m = repmat( ...
                atmosphereTruthIonosphereResidualByTower_m(:).', ...
                sim.numReceivers, ...
                1);

            truthTotal_m = ...
                atmosphereTruthDelayRt_m + truthResidualByReceiverTower_m;

            truthTroposphereTotal_m = ...
                atmosphereTruthTroposphereRt_m + ...
                truthTroposphereResidualByReceiverTower_m;

            truthIonosphereTotal_m = ...
                atmosphereTruthIonosphereRt_m + ...
                truthIonosphereResidualByReceiverTower_m;

            history.atmosphere_truth_total_by_receiver_tower_m(:, :, k) = ...
                truthTotal_m;

            history.atmosphere_truth_troposphere_total_by_receiver_tower_m(:, :, k) = ...
                truthTroposphereTotal_m;

            history.atmosphere_truth_ionosphere_total_by_receiver_tower_m(:, :, k) = ...
                truthIonosphereTotal_m;

            history = HistoryRecorder.recordPropagationDiagnostics( ...
                sim, history, k, visibilityMask);

            history = HistoryRecorder.recordAtmosphereBudget( ...
                sim, ...
                history, ...
                k, ...
                atmosphereTruthDelayRt_m, ...
                atmosphereTruthTroposphereRt_m, ...
                atmosphereTruthIonosphereRt_m, ...
                truthResidualByReceiverTower_m, ...
                truthTroposphereResidualByReceiverTower_m, ...
                truthIonosphereResidualByReceiverTower_m, ...
                truthTotal_m, ...
                truthTroposphereTotal_m, ...
                truthIonosphereTotal_m, ...
                atmosphereModelDelayRt_m, ...
                atmosphereModelTroposphereRt_m, ...
                atmosphereModelIonosphereRt_m);
            history = HistoryRecorder.recordNonAtmosphericBudget( ...
                sim, ...
                history, ...
                k, ...
                visibilityMask, ...
                towersEci, ...
                receiverEci);
        end
    end

