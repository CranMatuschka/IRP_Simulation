            history.true_range_by_receiver_tower_m(:, :, k) = trueRangeRt;
            history.los_unit_eci_by_receiver_tower(:, :, :, k) = losRt;
            history.visibility_mask_by_receiver_tower(:, :, k) = visibilityMask;
