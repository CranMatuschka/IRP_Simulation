        function covariance = atmosphereCovarianceForEpoch(sim)
            covariance = struct( ...
                'residualTroposphereSigma_m', 0.0, ...
                'residualIonosphereSigma_m', 0.0, ...
                'sigma_m', 0.0, ...
                'variance_m2', 0.0);

            if isempty(sim.measurementModel) || ...
                    isempty(sim.measurementModel.modelAtmosphere)
                return;
            end

            modelAtmosphere = sim.measurementModel.modelAtmosphere;

            if modelAtmosphere.enableTroposphere
                covariance.residualTroposphereSigma_m = ...
                    double(modelAtmosphere.residualTroposphereSigma_m);
            end

            if modelAtmosphere.enableIonosphere
                covariance.residualIonosphereSigma_m = ...
                    double(modelAtmosphere.residualIonosphereSigma_m);
            end

            covariance.variance_m2 = ...
                covariance.residualTroposphereSigma_m^2 + ...
                covariance.residualIonosphereSigma_m^2;
            covariance.sigma_m = sqrt(covariance.variance_m2);
        end
        
        function history = recordNonAtmosphericBudget( ...
                sim, history, k, visibilityMask, towersEci, truthReceiverEci)

            if ~isfield(history, 'non_atmospheric') || ...
                    isempty(sim.measurementModel)
                return;
            end

            componentNames = [ ...
                "total", ...
                "hardware", ...
                "antenna", ...
                "multipath", ...
                "tower_survey", ...
                "legacy_sagnac"];

            modelAsset = sim.truthAsset;
            modelReceiverEci = truthReceiverEci;

            if isprop(sim, 'estAsset') && ~isempty(sim.estAsset)
                modelAsset = sim.estAsset;
                modelReceiverEci = sim.estAsset.receiverPositionsEci();
            end

            for rx = 1:sim.numReceivers
                for twr = 1:sim.numTowers
                    if ~visibilityMask(rx, twr)
                        continue;
                    end

                    [~, ~, truthBudget] = ...
                        sim.measurementModel.nonAtmosphericErrorBudget_m( ...
                        twr, ...
                        rx, ...
                        Clock.julianDateFromDatetime( ...
                        sim.simConfig.simulation.startUtc + ...
                        seconds(sim.time_s(k))), ...
                        towersEci(:, twr), ...
                        truthReceiverEci(:, rx), ...
                        sim.truthAsset);

                    [~, ~, modelBudget] = ...
                        sim.measurementModel.nonAtmosphericErrorBudget_m( ...
                        twr, ...
                        rx, ...
                        Clock.julianDateFromDatetime( ...
                        sim.simConfig.simulation.startUtc + ...
                        seconds(sim.time_s(k))), ...
                        towersEci(:, twr), ...
                        modelReceiverEci(:, rx), ...
                        modelAsset);

                    for componentIndex = 1:numel(componentNames)
                        componentName = componentNames(componentIndex);
                        fieldName = char(componentName + "_m");
                        budgetField = char(componentName);

                        truthValue_m = truthBudget.(budgetField).truth_m;
                        modelValue_m = modelBudget.(budgetField).model_m;

                        history.non_atmospheric.truth.(fieldName)(rx, twr, k) = ...
                            truthValue_m;
                        history.non_atmospheric.model.(fieldName)(rx, twr, k) = ...
                            modelValue_m;
                        history.non_atmospheric.residual.(fieldName)(rx, twr, k) = ...
                            truthValue_m - modelValue_m;
                    end
                end
            end
        end

        function value = computeRms(x)
            x = x(:);
            value = sqrt(mean(x.^2, 'omitnan'));
        end
